import java.security.MessageDigest

// G05-R1 embedded Office engine module.
//
// This module never rebuilds the ~300 MB engine on the host (the official
// native producer requires a Linux toolchain). It packages the pinned, already
// verified staged payload produced by Main's preflight
// (prepare_office_payload.py over the official Collabora Office Mobile
// 26.04.4.2/code937 ARM64 APK, source revision
// 2333344185931274f9c49d6c12a408cefcef6844). Packaging inputs come ONLY from
// an explicitly supplied payload directory:
//   -Pfloe.office.payloadDir=<absolute path>   (or FLOE_OFFICE_PAYLOAD_DIR)
// A missing/mismatched payload fails actionably at asset/jniLibs merge; a
// compile-only or JVM-test invocation never requires the payload bytes.
//
// The official libc++_shared.so is deliberately NOT packaged: the app already
// ships its own libc++_shared.so (core/swiftbridge jniLibs, SHA-256
// b5d97c38a728afe28d341cda3369f512d35eaf9c680c1b0563cd6a63e395230f) and
// preflight proved all 257 strong C++ symbols the official libraries import
// are present there (NAME ONLY; ABI/load proof is a device gate owned by
// Main). No pickFirst, no runtime overwrite.
