// --- pinned payload verification --------------------------------------------
//
// Contract (Main review 2026-10-26): the consumed payload trees and the
// PAYLOAD_MANIFEST.json itself are declared Gradle inputs with explicit path
// sensitivity, so standard up-to-date checking safely reuses UNCHANGED inputs
// without rehashing; whenever the task actually executes (first run or any
// input change) it re-verifies everything it is about to certify: the manifest
// digest pinned from the signed-APK preflight output, the manifest structure,
// AND the SHA-256 of every consumed file (all assets + all selected libraries),
// never merely anchors. No old stamp is ever trusted for skipping.

abstract class VerifyOfficePayloadTask : DefaultTask() {
    @get:Input @get:Optional abstract val payloadDirPath: Property<String>

    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    @get:Optional
    abstract val manifestFile: RegularFileProperty

    @get:Input
    abstract val expectedManifestSha256: Property<String>

    // Consumed trees: every payload asset plus the 14 selected native
    // libraries. ABSOLUTE: the payload location is part of its identity on
    // this build host (Main's preflight directory).
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.ABSOLUTE)
    abstract val consumedAssets: ConfigurableFileCollection

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.ABSOLUTE)
    abstract val consumedLibraries: ConfigurableFileCollection

    @get:Input abstract val pinnedLibraries: MapProperty<String, String>
    @get:Input abstract val expectedManifestFiles: Property<Int>
    @get:Input abstract val expectedSelectedBytes: Property<Long>
    @get:OutputFile abstract val stampFile: RegularFileProperty

    private fun sha256(f: java.io.File): String {
        val md = MessageDigest.getInstance("SHA-256")
        f.inputStream().use { input ->
            val buf = ByteArray(1 shl 20)
            while (true) {
                val n = input.read(buf)
                if (n <= 0) break
                md.update(buf, 0, n)
            }
        }
        return md.digest().joinToString("") { "%02x".format(it) }
    }

    @TaskAction
    fun verify() {
        val dirPath = payloadDirPath.orNull
        val manifest = manifestFile.orNull?.asFile
        require(!dirPath.isNullOrBlank() && manifest != null && manifest.isFile) {
            "Floe Office payload is not configured. Set -Pfloe.office.payloadDir=<path to the " +
                "staged directory produced by core/officeengine/tools/prepare_payload.py (or env FLOE_OFFICE_PAYLOAD_DIR). This module " +
                "packages pinned prebuilt ARM64 libraries + assets only; it never rebuilds the " +
                "engine on the host and never ships a stub payload."
        }
        // 1. The manifest itself is pinned (its bytes are the preflight's
        //    authoritative per-file record over the signed APK's contents).
        val manifestSha = sha256(manifest)
        require(manifestSha == expectedManifestSha256.get()) {
            "Office producer manifest digest $manifestSha != pinned ${expectedManifestSha256.get()}"
        }
        val parsed = groovy.json.JsonSlurper().parse(manifest) as Map<*, *>
        @Suppress("UNCHECKED_CAST")
        val files = parsed["files"] as Map<String, Map<String, *>>
        require(files.size == expectedManifestFiles.get()) {
            "PAYLOAD_MANIFEST file entries ${files.size} != pinned ${expectedManifestFiles.get()}"
        }
        require((parsed["selectedBytes"] as Number).toLong() == expectedSelectedBytes.get()) {
            "PAYLOAD_MANIFEST selectedBytes mismatch against pin ${expectedSelectedBytes.get()}"
        }
        require((parsed["nativeLibraries"] as Number).toInt() == pinnedLibraries.get().size + 1) {
            "PAYLOAD_MANIFEST nativeLibraries does not equal selected libraries + excluded libc++"
        }

        // 2. Cross-check module pins against the manifest record.
        pinnedLibraries.get().forEach { (name, sha) ->
            val entry = files["lib/arm64-v8a/$name"]
            require(entry != null && entry["sha256"] == sha) {
                "Pinned library $name is absent or disagrees with the manifest record"
            }
        }
        require("libc++_shared.so" !in pinnedLibraries.get().keys) {
            "The official libc++_shared.so must never be packaged beside the app's own libc++"
        }

        // 3. Every consumed file on disk must match the manifest hash. This
        //    covers ALL packaged assets (not just anchors) and the 14 libs.
        //    asFileTree expands directory registrations to their files.
        val consumed = consumedAssets.asFileTree.files + consumedLibraries.asFileTree.files
        val expectedPaths = files.keys.filter { path ->
            path.startsWith("assets/") ||
                (path.startsWith("lib/arm64-v8a/") && path.removePrefix("lib/arm64-v8a/") in pinnedLibraries.get().keys)
        }
        require(consumed.size == expectedPaths.size) {
            "Consumed payload file count ${consumed.size} != manifest selection ${expectedPaths.size}"
        }
        val payloadRoot = dirPath.removeSuffix("/")
        consumed.forEach { f ->
            val rel = f.absolutePath.removePrefix(payloadRoot).removePrefix("/")
            val entry = files[rel]
            require(entry != null) { "Consumed payload file not recorded in manifest: $rel" }
            require(f.isFile) { "Consumed payload file missing on disk: $rel" }
            require(f.length() == (entry["bytes"] as Number).toLong()) {
                "Consumed payload file size drift: $rel"
            }
            val actual = sha256(f)
            require(actual == entry["sha256"]) { "Consumed payload file SHA-256 mismatch: $rel" }
        }

        val stamp = stampFile.get().asFile
        stamp.parentFile?.mkdirs()
        stamp.writeText(
            "payloadDir=$dirPath manifestSha256=$manifestSha files=${files.size} " +
                "consumed=${consumed.size} deepVerified=true\n",
        )
    }
}

abstract class StageOfficeJniLibsTask : DefaultTask() {
    @get:Input @get:Optional abstract val payloadDirPath: Property<String>

    // Actual content identity: any byte change under lib/arm64-v8a invalidates
    // the staged output even when the payload path itself is unchanged.
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.ABSOLUTE)
    abstract val consumedLibraries: ConfigurableFileCollection

    @get:Input abstract val pinnedLibraries: MapProperty<String, String>
    @get:OutputDirectory abstract val outDir: DirectoryProperty

    @TaskAction
    fun stage() {
        val dirPath = payloadDirPath.orNull
        require(!dirPath.isNullOrBlank()) {
            "Floe Office payload is not configured (see :core:officeengine build header). " +
                "APK packaging of the Office engine requires -Pfloe.office.payloadDir or " +
                "env FLOE_OFFICE_PAYLOAD_DIR."
        }
        val out = outDir.get().asFile
        val abi = File(out, "arm64-v8a").also { it.mkdirs() }
        val md = MessageDigest.getInstance("SHA-256")
        pinnedLibraries.get().forEach { (name, expectedSha) ->
            val src = File(dirPath, "lib/arm64-v8a/$name")
            val dst = File(abi, name)
            require(src.isFile) { "Pinned native library missing in payload: $src" }
            md.reset()
            val buf = ByteArray(1 shl 20)
            src.inputStream().use { input ->
                dst.outputStream().buffered().use { output ->
                    while (true) {
                        val n = input.read(buf)
                        if (n <= 0) break
                        md.update(buf, 0, n)
                        output.write(buf, 0, n)
                    }
                }
            }
            val actual = md.digest().joinToString("") { "%02x".format(it) }
            require(actual == expectedSha) {
                "Staged library $name SHA mismatch: $actual != $expectedSha (delete the module " +
                    "build/office-engine directory and rerun against the pinned payload)"
            }
        }
        // Fail closed if a payload directory ever gains unexpected engine libs.
        val extra = abi.listFiles { it.name.endsWith(".so") && it.name !in pinnedLibraries.get().keys }
        require(extra.isNullOrEmpty()) {
            "Unexpected packaged native libraries: ${extra?.map { it.name }}"
        }
    }
}

abstract class PrepareOfficeAssetsTask : DefaultTask() {
    @get:Input @get:Optional abstract val payloadDirPath: Property<String>

    // Actual content identity: any byte change under assets/ invalidates the
    // prepared output even when the payload path itself is unchanged. The
    // per-file SHA authority runs first (verifyOfficeEnginePayload) and hashes
    // every consumed asset at the changed-input boundary.
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.ABSOLUTE)
    abstract val consumedAssets: ConfigurableFileCollection

    @get:Input abstract val anchorAssets: MapProperty<String, String>
    @get:InputDirectory @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val overlayDirectory: DirectoryProperty
    @get:InputFile @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val overlayManifest: RegularFileProperty
    @get:OutputDirectory abstract val outDir: DirectoryProperty

    private fun sha256(f: java.io.File): String {
        val md = MessageDigest.getInstance("SHA-256")
        f.inputStream().use { input ->
            val buf = ByteArray(1 shl 20)
            while (true) {
                val n = input.read(buf)
                if (n <= 0) break
                md.update(buf, 0, n)
            }
        }
        return md.digest().joinToString("") { "%02x".format(it) }
    }

    @TaskAction
    fun prepare() {
        val dirPath = payloadDirPath.orNull
        require(!dirPath.isNullOrBlank()) {
            "Floe Office payload is not configured (see :core:officeengine build header)."
        }
        val srcRoot = File(dirPath, "assets")
        require(srcRoot.isDirectory) { "Payload assets root missing: $srcRoot" }
        val out = outDir.get().asFile
        // This is this task's generated output only. Start clean so removed
        // overlays cannot survive an incremental build as stale assets.
        require(!out.exists() || out.deleteRecursively()) { "Cannot clear generated Office assets" }
        // copyRecursively (no onError override) propagates IO failures as
        // task exceptions: an asset copy failure fails the build, never a
        // partial silent success.
        srcRoot.copyRecursively(out, overwrite = true)
        val copied = out.walkTopDown().filter { it.isFile }.count()
        val sourceCount = srcRoot.walkTopDown().filter { it.isFile }.count()
        require(copied == sourceCount) { "Asset copy count mismatch: $copied != $sourceCount" }
        // Integrity anchors from the payload manifest must survive copying
        // (viewer page + the upstream license/notice obligations we ship).
        anchorAssets.get().forEach { (rel, sha) ->
            val f = File(out, rel)
            require(f.isFile) { "Anchored Office asset missing after copy: $rel" }
            require(sha256(f) == sha) { "Anchored Office asset corrupted: $rel" }
        }
        // Producer inputs remain immutable and independently verified above.
        // Floe's explicit, source-controlled additions/replacements are then
        // applied with original AND resulting byte identities in the manifest.
        val overlayRoot = overlayDirectory.get().asFile.canonicalFile
        val manifest = groovy.json.JsonSlurper().parse(overlayManifest.get().asFile) as Map<*, *>
        require(manifest["schema"] == 1) { "Unsupported Office overlay manifest" }
        val entries = manifest["entries"] as? List<*> ?: error("Office overlay entries missing")
        val usedSources = mutableSetOf<String>()
        val destinations = mutableSetOf<String>()
        var expectedCount = sourceCount
        fun resolve(root: File, rel: String): File {
            require(rel.isNotEmpty() && !rel.startsWith("/") && !rel.contains('\\') &&
                rel.split('/').none { it.isEmpty() || it == "." || it == ".." }) { "Unsafe Office overlay path" }
            val f = File(root, rel).canonicalFile
            require(f.path.startsWith(root.canonicalPath + File.separator)) { "Office overlay escapes root" }
            return f
        }
        entries.forEach { value ->
            val entry = value as? Map<*, *> ?: error("Malformed Office overlay entry")
            val rel = entry["destination"] as? String ?: error("Office overlay destination missing")
            require(destinations.add(rel)) { "Duplicate Office overlay destination: $rel" }
            require(rel != "license.html" && rel != "notice.txt") { "Original Office notices must remain unchanged" }
            val original = resolve(srcRoot, rel)
            val target = resolve(out, rel)
            val operation = entry["operation"] as? String ?: error("Office overlay operation missing")
            when (operation) {
                "add" -> {
                    require(!original.exists() && entry["originalSha256"] == null) { "Office add overwrites producer asset: $rel" }
                    expectedCount++
                }
                "replace", "remove" -> {
                    val expected = entry["originalSha256"] as? String ?: error("Original Office overlay digest missing: $rel")
                    require(original.isFile && sha256(original) == expected) { "Original Office asset changed: $rel" }
                    if (operation == "remove") {
                        require(target.delete()) { "Cannot remove generated Office branding asset: $rel" }
                        expectedCount--
                    }
                }
                else -> error("Unknown Office overlay operation")
            }
            if (operation != "remove") {
                val source = entry["source"] as? String ?: error("Office overlay source missing")
                require(usedSources.add(source)) { "Duplicate Office overlay source" }
                val input = resolve(overlayRoot, source)
                val digest = entry["sha256"] as? String ?: error("Office overlay digest missing")
                require(input.isFile && sha256(input) == digest) { "Office overlay source digest mismatch: $source" }
                require(target.parentFile.isDirectory || target.parentFile.mkdirs()) { "Cannot create Office overlay parent" }
                input.copyTo(target, overwrite = true)
                require(sha256(target) == digest) { "Office overlay output digest mismatch: $rel" }
            }
        }
        val actualSources = overlayRoot.walkTopDown().filter { it.isFile }
            .map { it.relativeTo(overlayRoot).invariantSeparatorsPath }.toSet()
        require(actualSources == usedSources) { "Unlisted Office overlay sources" }
        require(out.walkTopDown().count { it.isFile } == expectedCount) { "Office final asset count mismatch" }
        // Even after explicit overlays the original licence/NOTICE bytes are
        // unchanged; no transform can silently remove required attribution.
        listOf("license.html", "notice.txt").forEach { rel ->
            require(sha256(File(out, rel)) == sha256(File(srcRoot, rel))) { "Office attribution changed" }
        }
    }
}

val pinsFile = file("payload-pins.json")
val pins = groovy.json.JsonSlurper().parse(pinsFile) as Map<*, *>
val payloadRecord = pins["payload"] as Map<*, *>
@Suppress("UNCHECKED_CAST")
val pinnedLibs = (pins["libraries"] as Map<String, Any?>).mapValues { it.value.toString() }
@Suppress("UNCHECKED_CAST")
val pinnedAssets = (pins["anchorAssets"] as Map<String, Any?>).mapValues { it.value.toString() }
val pinnedCount = (payloadRecord["files"] as Number).toInt()
val pinnedBytes = (payloadRecord["selectedBytes"] as Number).toLong()
val pinnedManifestSha = payloadRecord["manifestSha256"].toString()

android {
    packaging.jniLibs.keepDebugSymbols += pinnedLibs.keys.map { "**/$it" }
}

// Absent payload config must reach the task action's actionable error, not a
// provider resolution failure: fall back to empty, optional-safe inputs.
val consumedAssetTree: Provider<ConfigurableFileCollection> = payloadDir
    .map { objects.fileCollection().from(File(it, "assets")) }
    .orElse(objects.fileCollection())
val consumedLibTree: Provider<ConfigurableFileCollection> = payloadDir
    .map { dir ->
        objects.fileCollection().from(
            *pinnedLibs.keys.map { name -> File(dir, "lib/arm64-v8a/$name") }.toTypedArray(),
        )
    }
    .orElse(objects.fileCollection())
val manifestFileProvider: Provider<RegularFile> = providers.provider {
    layout.projectDirectory.file("producer-manifest.json")
}

val verifyOfficePayload = tasks.register<VerifyOfficePayloadTask>("verifyOfficeEnginePayload") {
    payloadDirPath.set(payloadDir)
    manifestFile.set(manifestFileProvider)
    expectedManifestSha256.set(pinnedManifestSha)
    consumedAssets.from(consumedAssetTree)
    consumedLibraries.from(consumedLibTree)
    pinnedLibraries.set(pinnedLibs)
    expectedManifestFiles.set(pinnedCount)
    expectedSelectedBytes.set(pinnedBytes)
    stampFile.set(layout.buildDirectory.file("office-engine/payload-verified.stamp"))
}

val stageOfficeEngineJniLibs = tasks.register<StageOfficeJniLibsTask>("stageOfficeEngineJniLibs") {
    payloadDirPath.set(payloadDir)
    consumedLibraries.from(consumedLibTree)
    pinnedLibraries.set(pinnedLibs)
    outDir.set(layout.buildDirectory.dir("office-engine/jniLibs"))
    dependsOn(verifyOfficePayload)
}

val prepareOfficeEngineAssets = tasks.register<PrepareOfficeAssetsTask>("prepareOfficeEngineAssets") {
    payloadDirPath.set(payloadDir)
    consumedAssets.from(consumedAssetTree)
    anchorAssets.set(pinnedAssets)
    overlayDirectory.set(layout.projectDirectory.dir("overlays"))
    overlayManifest.set(layout.projectDirectory.file("asset-overlays.json"))
    outDir.set(layout.buildDirectory.dir("office-engine/assets"))
    dependsOn(verifyOfficePayload)
}

// First wiring path: AGP variant sources (merge consumes the generated
// directories through the official API, so packaging sees them without task
// name guessing).
androidComponents.onVariants { variant ->
    variant.sources.assets?.addGeneratedSourceDirectory(
        prepareOfficeEngineAssets,
        PrepareOfficeAssetsTask::outDir,
    )
    variant.sources.jniLibs?.addGeneratedSourceDirectory(
        stageOfficeEngineJniLibs,
        StageOfficeJniLibsTask::outDir,
    )
}

// Belt-and-braces on AGP internal task names: merges always wait for the
// staged inputs (no-op if the variant API already wired them).
tasks.configureEach {
    if (name.startsWith("merge") && name.contains("JniLib")) {
        dependsOn(stageOfficeEngineJniLibs)
    } else if (name.startsWith("copy") && name.contains("JniLib")) {
        dependsOn(stageOfficeEngineJniLibs)
    } else if (name.startsWith("merge") && name.contains("Assets")) {
        dependsOn(prepareOfficeEngineAssets)
    } else if (name.contains("lint", ignoreCase = true)) {
        // AGP's lint model reads generated asset directories directly; its
        // variant source wiring does not carry the producing task dependency.
        dependsOn(prepareOfficeEngineAssets, stageOfficeEngineJniLibs)
    }
}

