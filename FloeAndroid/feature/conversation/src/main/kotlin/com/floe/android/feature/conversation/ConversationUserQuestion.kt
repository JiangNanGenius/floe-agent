// Presentation contract for durable, task-bound user questions on Android.
//
// A question is ordinary conversation data, never an approval: it grants no
// authority. The native store is the sole settlement authority; this module
// carries a bounded projection plus the user's in-progress UI state and never
// mints request/question/run identities, answer receipts or question ids.
package com.floe.android.feature.conversation

import androidx.compose.ui.text.input.TextFieldValue

enum class UserQuestionWaitPolicyUi(val raw: String) {
    REQUIRED("required"),
    OPTIONAL_CONTINUE("optionalContinue"),
    OPTIONAL_DEADLINE("optionalDeadline");

    val blocksWork: Boolean get() = this != OPTIONAL_CONTINUE

    companion object {
        fun from(raw: String): UserQuestionWaitPolicyUi =
            entries.firstOrNull { it.raw == raw } ?: REQUIRED
    }
}

enum class UserQuestionSelectionModeUi(val raw: String) {
    SINGLE("single"),
    MULTIPLE("multiple");

    companion object {
        fun from(raw: String): UserQuestionSelectionModeUi =
            entries.firstOrNull { it.raw == raw } ?: SINGLE
    }
}

enum class UserQuestionStatusUi(val raw: String) {
    PENDING("pending"),
    ANSWERED("answered"),
    EXPIRED("expired"),
    CANCELLED("cancelled");

    val isSettled: Boolean get() = this != PENDING
    val isPending: Boolean get() = this == PENDING

    companion object {
        fun from(raw: String): UserQuestionStatusUi =
            entries.firstOrNull { it.raw == raw } ?: PENDING
    }
}

data class UserQuestionOptionUi(
    val id: String,
    val label: String,
    val detail: String? = null,
)

data class UserQuestionPromptUi(
    val questionId: String,
    val requestId: String,
    val runId: String,
    val text: String,
    val options: List<UserQuestionOptionUi>,
    val selectionMode: UserQuestionSelectionModeUi,
    val allowsFreeText: Boolean,
    val waitPolicy: UserQuestionWaitPolicyUi,
    val deadlineLabel: String?,
    val status: UserQuestionStatusUi,
    val revision: Int,
    val answerNonce: String,
    val requestDigest: String,
    val answeredLabels: List<String> = emptyList(),
    val answerSourceRaw: String? = null,
    val answerFreeText: String? = null,
) {
    val isTextOnly: Boolean get() = options.isEmpty()
    val isPending: Boolean get() = status == UserQuestionStatusUi.PENDING
    val canAcceptFreeText: Boolean get() = isTextOnly || allowsFreeText
}

data class UserQuestionSnapshotUi(
    val requestId: String,
    val requestDigest: String,
    val conversationId: String,
    val runId: String,
    val stateRaw: String,
    val isEphemeral: Boolean,
    val questions: List<UserQuestionPromptUi>,
    val currentQuestionId: String?,
) {
    val currentQuestion: UserQuestionPromptUi?
        get() = questions.firstOrNull { it.isPending }

    val pendingBlockingCount: Int
        get() = questions.count { it.isPending && it.waitPolicy.blocksWork }

    val hasPending: Boolean get() = questions.any { it.isPending }
}

/** Exact identity of one answer the user is submitting. The nonce is issued by
 * the native snapshot and regenerated by the host before settlement; a stale
 * sheet or notification action can never answer a newer revision. */
data class UserQuestionAnswerRequestUi(
    val requestId: String,
    val requestDigest: String,
    val questionId: String,
    val runId: String,
    val expectedRevision: Int,
    val answerNonce: String,
    val selectedOptionIds: List<String>,
    val freeText: String?,
)

data class UserQuestionAnswerReceiptUi(
    val requestId: String,
    val questionId: String,
    val statusRaw: String,
    val revision: Int,
    val accepted: Boolean,
    val alreadySettled: Boolean,
    val requestStateRaw: String,
    val selectedLabels: List<String> = emptyList(),
) {
    val settled: Boolean
        get() = accepted || alreadySettled ||
            statusRaw == UserQuestionStatusUi.ANSWERED.raw ||
            statusRaw == UserQuestionStatusUi.EXPIRED.raw ||
            statusRaw == UserQuestionStatusUi.CANCELLED.raw
}

/** In-progress UI fields. Derived from the CURRENT snapshot on first render;
 * user edits never consume the native answer CAS revision. */
data class UserQuestionDraftUi(
    val questionId: String,
    val selectedOptionIds: Set<String> = emptySet(),
    val freeText: TextFieldValue = TextFieldValue(""),
)

object UserQuestionDraftPolicy {
    /** Single-select replaces; multi-select toggles. Unknown ids are ignored
     * (the native answer validation remains authoritative). */
    fun toggle(
        current: Set<String>,
        optionId: String,
        mode: UserQuestionSelectionModeUi,
        validIds: Set<String>,
    ): Set<String> {
        if (optionId !in validIds) return current
        return when (mode) {
            UserQuestionSelectionModeUi.SINGLE -> setOf(optionId)
            UserQuestionSelectionModeUi.MULTIPLE ->
                if (optionId in current) current - optionId else current + optionId
        }
    }

    /** Mirrors the native answer rules so the Send control is disabled with an
     * incomplete selection instead of pretending the call can settle. */
    fun canSubmit(
        question: UserQuestionPromptUi,
        selected: Set<String>,
        freeText: String,
    ): Boolean {
        if (!question.isPending || !question.status.isPending) return false
        val text = freeText.trim()
        if (text.length > 1_000) return false
        if (question.isTextOnly) {
            return selected.isEmpty() && text.isNotEmpty()
        }
        if (question.selectionMode == UserQuestionSelectionModeUi.SINGLE) {
            if (selected.size != 1) return false
        } else if (selected.isEmpty()) {
            return false
        }
        if (text.isNotEmpty() && !question.allowsFreeText) return false
        return true
    }

    fun answer(
        question: UserQuestionPromptUi,
        selected: Set<String>,
        freeText: String,
    ): Pair<List<String>, String?> {
        val text = freeText.trim().takeIf { it.isNotEmpty() }
        return selected.toList() to text
    }
}
