package com.floe.android.phonecontrol

import java.util.UUID

internal fun testOwner(
    task: String = "11111111-1111-1111-1111-111111111111",
    run: String = "22222222-2222-2222-2222-222222222222",
): PhoneControlOwner = PhoneControlOwner(UUID.fromString(task), UUID.fromString(run))

internal fun testPrincipal(
    owner: PhoneControlOwner = testOwner(),
    epoch: Long = 7,
    generation: Long = 3,
    packages: Set<String> = setOf("com.example.app"),
    grantID: UUID? = null,
    callID: String? = null,
): PhoneControlPrincipal = PhoneControlPrincipal(
    owner = owner,
    epoch = epoch,
    generation = generation,
    allowedPackages = packages,
    grantID = grantID,
    callID = callID,
)

internal fun testGrant(
    owner: PhoneControlOwner = testOwner(),
    epoch: Long = 7,
    generation: Long = 3,
    packages: Set<String> = setOf("com.example.app"),
    globalNavigation: Boolean = true,
    screenshot: Boolean = true,
    grantID: UUID? = null,
): PhoneControlGrant = PhoneControlGrant(
    owner = owner,
    epoch = epoch,
    generation = generation,
    allowedPackages = packages,
    allowGlobalNavigation = globalNavigation,
    allowScreenshot = screenshot,
    grantID = grantID,
)

internal fun testNode(
