    selected = false,
    checkable = false,
    checked = false,
    password = password,
    redacted = redacted,
    truncated = truncated,
)

internal fun testObservation(
    nodes: List<PhoneControlNode> = listOf(testNode()),
    owner: PhoneControlOwner = testOwner(),
    observationId: String = "observation-1",
    packageName: String? = "com.example.app",
    sensitiveWindow: Boolean = nodes.any { it.password || it.redacted },
): PhoneControlObservation = PhoneControlObservation(
    observationId = observationId,
    owner = owner,
    fenceGeneration = 2,
    pageGeneration = 4,
    capturedAtElapsedRealtimeMillis = 1_000,
    expiresAtElapsedRealtimeMillis = 31_000,
    packageName = packageName,
    windowId = 12,
    windowType = 1,
    windowTitle = "Example",
    displayId = 0,
    rootClassName = "android.widget.FrameLayout",
    sensitiveWindow = sensitiveWindow,
    screenshotSupport = PhoneControlScreenshotSupport.DISPLAY,
    nodes = nodes,
    truncated = false,
    maxDepthReached = false,
)

