#!/usr/bin/env python3
"""Record exact native inputs and packaged library hashes.

Generation (explicit output directory, used by build-swift.sh):

    native-manifest.py PATH/TO/jniLibs/arm64-v8a

writes PATH/TO/jniLibs/native-manifest.json (the output directory's parent).

Read-only drift check (never writes anything):

    native-manifest.py PATH/TO/jniLibs/arm64-v8a --check [--manifest FILE]

The manifest records every Swift source path that compiles into the shared
core (overlay paths AND their resolved original-source targets), every
C/C++/header/modulemap input of the vendored SQLite/CZLib C targets, the Swift
package manifest, the generated Package.resolved and the module Gradle
dependency lock (with the exact pinned revisions), JNI/CMake inputs, the
native build/toolchain scripts, the trusted security corpus resource plus its
exported APK asset and toolchains.lock.json. A hash documents the exact bytes
read when the manifest was generated; it is not retroactive proof that an
earlier binary was built from those bytes. Regenerate after the final
serialized build and keep the source/APK provenance capture with the artifacts.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

SCRIPT = Path(__file__).resolve()
DEFAULT_ROOT = SCRIPT.parents[2]  # repository root

# Exact files that define the native module and the toolchain used to build it.
BUILD_INPUTS = (
    "FloeAndroid/scripts/build-swift.sh",
    "FloeAndroid/scripts/env.sh",
    "FloeAndroid/scripts/configure-swift-sdk.py",
    "FloeAndroid/toolchains.lock.json",
    "FloeAndroid/core/swiftbridge/build.gradle.kts",
    "FloeAndroid/core/linuxauthoritybridge/build.gradle.kts",
)

# Actual compiled C/C++/header/modulemap inputs of the vendored C targets
# (GRDBSQLite's SQLite 3.54.1 amalgamation, CZLib's zlib shim). These were
# absent from the first manifest revision, so a C-source change could drift
# without inputDigest movement; they are hashed here.
C_INPUT_SUFFIXES = (".c", ".cc", ".cpp", ".cxx", ".h", ".hh", ".hpp", ".hxx",
                    ".inl")
C_INPUT_NAMES = ("module.modulemap",)

# Generated dependency/config locks actually consumed by the build. Package.resolved
# is regenerated by SwiftPM from the exact-revision pin in Package.swift; the
# module Gradle lock pins the androidTest dependency set. Neither is rewritten
# by this tool — --check only reads them.
RESOLVED_INPUTS = (
    "FloeAndroid/shared/Package.resolved",
    "FloeAndroid/core/swiftbridge/gradle.lockfile",
)

# These anchors must exist; their absence must not silently produce a smaller
# manifest that still looks valid.
REQUIRED_INPUTS = (
    "FloeAndroid/shared/Package.swift",
    "FloeAndroid/shared/Package.resolved",
    "FloeAndroid/shared/Sources/GRDBSQLite/sqlite3.c",
    "FloeAndroid/shared/Sources/GRDBSQLite/sqlite3.h",
    "FloeAndroid/shared/Sources/GRDBSQLite/module.modulemap",
    "FloeAndroid/shared/Sources/GRDBSQLite/shim.h",
    "FloeAndroid/shared/Sources/CZLib/module.modulemap",
    "FloeAndroid/core/swiftbridge/gradle.lockfile",
    "FloeAndroid/core/swiftbridge/src/main/cpp/floe_jni.cpp",
    "FloeAndroid/core/swiftbridge/src/main/cpp/CMakeLists.txt",
) + BUILD_INPUTS + RESOLVED_INPUTS

# Trusted security corpus: the exact upstream resource and the exported APK
# asset must both exist and be byte-identical (build-swift.sh performs the
# pinned-hash copy; this manifest keeps them inside the provenance digest).
SECURITY_CORPUS = (
    "FloeAndroid/shared/Sources/FloeSecurity/Resources/catastrophic-patterns.json",
    "FloeAndroid/core/swiftbridge/src/main/assets/security/catastrophic-patterns.json",
)

NATIVE_SUFFIXES = (
    ".c",
    ".cc",
    ".cpp",
    ".cxx",
    ".h",
    ".hh",
    ".hpp",
    ".hxx",
    ".inl",
    ".cmake",
)


class ManifestError(Exception):
    pass


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def repo_relative(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def add_required_file(root: Path, relative: str, mapping: dict) -> None:
    path = root / relative
    if not path.is_file():
        raise ManifestError("required input missing: %s" % relative)
    mapping[relative] = sha256_file(path)


def collect_swift_inputs(root: Path, shared_sources: dict, source_links: dict) -> None:
    package = root / "FloeAndroid/shared/Package.swift"
    if not package.is_file():
        raise ManifestError("required input missing: %s" % repo_relative(root, package))
    add_required_file(root, repo_relative(root, package), shared_sources)

    sources_dir = root / "FloeAndroid/shared/Sources"
    if not sources_dir.is_dir():
        raise ManifestError("shared Swift sources directory missing: %s"
                            % repo_relative(root, sources_dir))
    swift_files = sorted(p for p in sources_dir.rglob("*.swift")
                         if p.is_file() or p.is_symlink())
    if not swift_files:
        raise ManifestError("no Swift sources found under %s"
                            % repo_relative(root, sources_dir))

    resolved_root = root.resolve()
    for path in swift_files:
        relative = repo_relative(root, path)
        if not path.is_file():
            raise ManifestError("Swift source is unreadable or a broken symlink: %s"
                                % relative)
        shared_sources[relative] = sha256_file(path)
        if not path.is_symlink():
            continue
        target = path.resolve()
        if not target.is_file():
            raise ManifestError("Swift source symlink target missing: %s -> %s"
                                % (relative, target))
        try:
            target_relative = target.relative_to(resolved_root).as_posix()
        except ValueError:
            raise ManifestError(
                "Swift source symlink resolves outside the repository: %s -> %s"
                % (relative, target)
            )
        source_links[relative] = target_relative
        # Record the actual source bytes too, so the manifest keeps working
        # when the original iOS path is inspected directly.
        shared_sources[target_relative] = sha256_file(target)


def collect_security_corpus(root: Path, resources: dict) -> None:
    """Hash the trusted corpus source and its exported APK asset, requiring
    byte-identical content (a re-encoded or replaced corpus must never be
    recorded as if it were the trusted resource)."""
    for relative in SECURITY_CORPUS:
        add_required_file(root, relative, resources)
    source = root / SECURITY_CORPUS[0]
    asset = root / SECURITY_CORPUS[1]
    if sha256_file(source) != sha256_file(asset):
        raise ManifestError("exported corpus asset differs from the upstream resource")


def collect_c_inputs(root: Path, c_inputs: dict, source_links: dict) -> None:
    """Hash every actual C/C++/header/modulemap input under the shared package
    (SQLite amalgamation, CZLib shim, modulemaps). Symlinks are resolved and
    their targets are recorded exactly like Swift links."""
    sources_dir = root / "FloeAndroid/shared/Sources"
    if not sources_dir.is_dir():
        raise ManifestError("shared Sources directory missing: %s"
                            % repo_relative(root, sources_dir))
    candidates = sorted(
        p for p in sources_dir.rglob("*")
        if (p.is_file() or p.is_symlink())
        and (p.suffix in C_INPUT_SUFFIXES or p.name in C_INPUT_NAMES)
    )
    if not candidates:
        raise ManifestError("no C/header/modulemap inputs found under %s"
                            % repo_relative(root, sources_dir))
    resolved_root = root.resolve()
    for path in candidates:
        relative = repo_relative(root, path)
        if not path.is_file():
            raise ManifestError("C input is unreadable or a broken symlink: %s"
                                % relative)
        c_inputs[relative] = sha256_file(path)
        if not path.is_symlink():
            continue
        target = path.resolve()
        try:
            target_relative = target.relative_to(resolved_root).as_posix()
        except ValueError:
            raise ManifestError("C input symlink resolves outside the repository: "
                                "%s -> %s" % (relative, target))
        source_links[relative] = target_relative
        c_inputs[target_relative] = sha256_file(target)


def collect_resolved_inputs(root: Path, resolved_inputs: dict,
                            resolved_pins: list) -> None:
    """Hash the generated dependency locks and record the exact pinned
    dependency revisions. Package.resolved must carry a 40-hex revision for
    every pin (no floating branch), and the swift-crypto resolved revision
    must equal the exact `revision:` pin declared in Package.swift. Nothing is
    rewritten; drift is reported by --check."""
    for relative in RESOLVED_INPUTS:
        add_required_file(root, relative, resolved_inputs)
    package_resolved = root / "FloeAndroid/shared/Package.resolved"
    try:
        data = json.loads(package_resolved.read_text(encoding="utf-8"))
    except ValueError as exc:
        raise ManifestError("Package.resolved is unreadable: %s" % exc)
    pins = data.get("pins")
    if not isinstance(pins, list) or not pins:
        raise ManifestError("Package.resolved has no pins")
    seen = set()
    for pin in pins:
        identity = pin.get("identity")
        state = pin.get("state") or {}
        revision = state.get("revision")
        if not identity or not isinstance(revision, str) or len(revision) != 40:
            raise ManifestError("Package.resolved pin lacks an exact revision: %r"
                                % (identity or pin))
        resolved_pins.append({
            "identity": identity,
            "location": pin.get("location"),
            "version": state.get("version"),
            "revision": revision,
        })
        seen.add(identity)
    package_text = (root / "FloeAndroid/shared/Package.swift").read_text(encoding="utf-8")
    declared = set(re.findall(r'revision:\s*"([0-9a-f]{40})"', package_text))
    crypto = next((p for p in resolved_pins if p["identity"] == "swift-crypto"), None)
    if crypto is None:
        raise ManifestError("Package.resolved does not pin swift-crypto")
    if declared and crypto["revision"] not in declared:
        raise ManifestError(
            "swift-crypto resolved revision %s does not match the Package.swift "
            "exact pin %s" % (crypto["revision"], sorted(declared)))
    resolved_pins.sort(key=lambda p: p["identity"])


def collect_native_inputs(root: Path, native_inputs: dict) -> None:
    candidates = set()
    for module in ("swiftbridge", "linuxauthoritybridge"):
        cpp_dir = root / f"FloeAndroid/core/{module}/src/main/cpp"
        if not cpp_dir.is_dir():
            raise ManifestError("JNI/CMake directory missing: %s" % repo_relative(root, cpp_dir))
        module_inputs = set()
        for path in cpp_dir.rglob("*"):
            if path.name == "CMakeLists.txt" or path.suffix in NATIVE_SUFFIXES:
                if not path.is_file():
                    raise ManifestError("native input is unreadable or a broken symlink: %s" % repo_relative(root, path))
                module_inputs.add(path)
        if not module_inputs:
            raise ManifestError("no JNI/CMake inputs found under %s" % repo_relative(root, cpp_dir))
        candidates.update(module_inputs)
    if not candidates:
        raise ManifestError("no JNI/CMake inputs found under %s"
                            % repo_relative(root, cpp_dir))
    for path in sorted(candidates):
        relative = repo_relative(root, path)
        native_inputs[relative] = sha256_file(path)

    for relative in BUILD_INPUTS:
        add_required_file(root, relative, native_inputs)


def collect_libraries(output: Path, product_library: str = "libFloeAndroidCore.so") -> dict:
    if not output.is_dir():
        raise ManifestError("native output directory missing: %s" % output)
    libraries = {}
    for path in sorted(output.glob("*.so")):
        if not path.is_file():
            raise ManifestError("packaged library is unreadable or a broken symlink: %s"
                                % path.name)
        libraries[path.name] = sha256_file(path)
    if not libraries:
        raise ManifestError("no packaged .so libraries found in %s" % output)
    if product_library not in libraries:
        raise ManifestError("%s missing from %s" % (product_library, output))
    return libraries


def input_digest(shared_sources: dict, native_inputs: dict,
                 source_links: dict, resources: dict, c_inputs: dict,
                 resolved_inputs: dict, resolved_pins: list) -> str:
    payload = json.dumps(
        {
            "sharedSources": shared_sources,
            "nativeInputs": native_inputs,
            "sourceLinks": source_links,
            "resources": resources,
            "cInputs": c_inputs,
            "resolvedInputs": resolved_inputs,
            "resolvedPins": resolved_pins,
        },
        sort_keys=True,
        ensure_ascii=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def require_anchors(root: Path) -> None:
    missing = [relative for relative in tuple(REQUIRED_INPUTS) + SECURITY_CORPUS
               if not (root / relative).is_file()]
    if missing:
        raise ManifestError("required input(s) missing: %s" % ", ".join(missing))


def build_manifest(root: Path, output: Path, product_library: str = "libFloeAndroidCore.so") -> dict:
    require_anchors(root)
    lock_path = root / "FloeAndroid/toolchains.lock.json"
    if not lock_path.is_file():
        raise ManifestError("required input missing: %s"
                            % repo_relative(root, lock_path))
    try:
        lock = json.loads(lock_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ManifestError("toolchains.lock.json is unreadable: %s" % exc)
    for key in ("swift", "ndk"):
        if not lock.get(key):
            raise ManifestError("toolchains.lock.json lacks %s" % key)

    shared_sources = {}
    source_links = {}
    native_inputs = {}
    resources = {}
    c_inputs = {}
    resolved_inputs = {}
    resolved_pins = []
    collect_swift_inputs(root, shared_sources, source_links)
    collect_c_inputs(root, c_inputs, source_links)
    collect_native_inputs(root, native_inputs)
    collect_security_corpus(root, resources)
    collect_resolved_inputs(root, resolved_inputs, resolved_pins)
    libraries = collect_libraries(output, product_library)

    return {
        "schemaVersion": 1,
        "productLibrary": product_library,
        "abi": "arm64-v8a",
        "swift": lock["swift"],
        "ndk": lock["ndk"],
        "inputDigest": input_digest(shared_sources, native_inputs, source_links,
                                   resources, c_inputs, resolved_inputs,
                                   resolved_pins),
        "sharedSources": shared_sources,
        "nativeInputs": native_inputs,
        "sourceLinks": source_links,
        "resources": resources,
        "cInputs": c_inputs,
        "resolvedInputs": resolved_inputs,
        "resolvedPins": resolved_pins,
        "libraries": libraries,
    }


def diff_manifests(recorded, computed, prefix=""):
    """Return human-readable differences between two manifest structures."""
    lines = []
    if type(recorded) is not type(computed):
        lines.append("%s: recorded type %s, computed type %s"
                     % (prefix or "<root>", type(recorded).__name__,
                        type(computed).__name__))
        return lines
    if isinstance(recorded, dict):
        for key in sorted(set(recorded) | set(computed)):
            label = "%s.%s" % (prefix, key) if prefix else str(key)
            if key not in computed:
                lines.append("%s: recorded but not computed" % label)
            elif key not in recorded:
                lines.append("%s: computed but not recorded" % label)
            else:
                lines.extend(diff_manifests(recorded[key], computed[key], label))
        return lines
    if recorded != computed:
        lines.append("%s: recorded %r, computed %r"
                     % (prefix or "<root>", recorded, computed))
    return lines


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Record or read-only check the Android native input manifest"
    )
    parser.add_argument("output", type=Path,
                        help="directory containing the packaged .so libraries")
    parser.add_argument("--check", action="store_true",
                        help="compare with the recorded manifest; never write")
    parser.add_argument("--manifest", type=Path,
                        help="manifest to compare against with --check "
                             "(default: OUTPUT/../native-manifest.json)")
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT,
                        help=argparse.SUPPRESS)
    parser.add_argument("--library", default="libFloeAndroidCore.so",
                        choices=("libFloeAndroidCore.so", "libFloeAndroidLinuxAuthority.so"),
                        help="exact Swift product required in this output")
    args = parser.parse_args(argv)

    if args.manifest is not None and not args.check:
        parser.error("--manifest is only valid with --check")

    root = args.root.resolve()
    output = args.output.resolve()
    try:
        computed = build_manifest(root, output, args.library)
    except (ManifestError, OSError) as exc:
        print("native-manifest: FAIL %s" % exc, file=sys.stderr)
        return 1

    if args.check:
        target = args.manifest if args.manifest is not None else \
            output.parent / "native-manifest.json"
        if not target.is_file():
            print("native-manifest: FAIL recorded manifest missing: %s"
                  % target, file=sys.stderr)
            return 1
        try:
            recorded = json.loads(target.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            print("native-manifest: FAIL recorded manifest is unreadable: %s"
                  % exc, file=sys.stderr)
            return 1
        drift = diff_manifests(recorded, computed)
        if drift:
            for line in drift:
                print("DRIFT %s" % line)
            print("native-manifest: drift detected; recorded manifest was not "
                  "rewritten (%s)" % target)
            return 1
        print("native-manifest: OK %d libraries, %d Swift path entries (%d "
              "overlay paths + %d resolved target files), %d C/header/modulemap "
              "inputs, %d native inputs, %d corpus resources, %d resolved inputs "
              "(%d pins) match %s"
              % (len(computed["libraries"]),
                 len(computed["sharedSources"]),
                 sum(1 for p in computed["sharedSources"]
                     if p.startswith("FloeAndroid/shared/")),
                 sum(1 for p in computed["sharedSources"]
                     if p.startswith("FloeAgent/")),
                 len(computed["cInputs"]), len(computed["nativeInputs"]),
                 len(computed["resources"]), len(computed["resolvedInputs"]),
                 len(computed["resolvedPins"]), target))
        return 0

    target = output.parent / "native-manifest.json"
    target.write_text(json.dumps(computed, indent=2) + "\n", encoding="utf-8")
    print("Native manifest: %d libraries, %d Swift path entries (%d overlay "
          "paths + %d resolved target files; not that many distinct compiled "
          "sources), %d C/header/modulemap inputs, %d native inputs, %d corpus "
          "resources, %d resolved inputs (%d exact pins) -> %s"
          % (len(computed["libraries"]),
             len(computed["sharedSources"]),
             sum(1 for p in computed["sharedSources"]
                 if p.startswith("FloeAndroid/shared/")),
             sum(1 for p in computed["sharedSources"]
                 if p.startswith("FloeAgent/")),
             len(computed["cInputs"]), len(computed["nativeInputs"]),
             len(computed["resources"]), len(computed["resolvedInputs"]),
             len(computed["resolvedPins"]), target))
    return 0


if __name__ == "__main__":
    sys.exit(main())
