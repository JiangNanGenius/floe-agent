/**
 * Exact cross-language wire vectors from the frozen Apple contract
 * (device-sync-android-20261124.9WKKBA, wire-examples.json; generated by the
 * production Swift Codable). These tests pin the Kotlin codec to the same
 * shapes: legacy peers must keep exchanging v1 archives, new capabilities
 * decode only in their exact forms, and every request/reply round-trips
 * without semantic drift. Numbers compare by value, objects/arrays deep.
 */
class DeviceSyncWireVectorTest {

    private fun vector(name: String): JSONObject {
        val root = JSONArray(fixtureBytes("wire-examples.json").decodeToString())
        for (index in 0 until root.length()) {
            val item = root.getJSONObject(index)
            if (item.getString("name") == name) return item
        }
        fail("missing wire vector $name")
        error("unreachable")
    }

    private fun fixtureBytes(name: String): ByteArray {
        val stream = checkNotNull(javaClass.getResourceAsStream("/devicesync/$name")) {
            "missing devicesync/$name test resource"
        }
        return stream.use { it.readBytes() }
    }

    private fun sha256(bytes: ByteArray): String {
        val digest = MessageDigest.getInstance("SHA-256").digest(bytes)
        val digits = "0123456789abcdef"
        return buildString(digest.size * 2) {
            digest.forEach { byte ->
                val value = byte.toInt()
                append(digits[(value ushr 4) and 0x0f])
                append(digits[value and 0x0f])
            }
        }
    }

    private fun assertJsonEquivalent(expected: Any?, actual: Any?, path: String) {
        when (expected) {
            null -> assertNull("$path expected null", actual?.takeUnless { it == JSONObject.NULL })
            is JSONObject -> {
                assertTrue("$path expected object, got $actual", actual is JSONObject)
                for (key in expected.keys()) {
                    assertJsonEquivalent(expected.get(key), (actual as JSONObject).opt(key), "$path.$key")
                }
                for (key in (actual as JSONObject).keys()) {
                    assertTrue("$path has unexpected key $key", expected.has(key))
                }
            }
            is JSONArray -> {
                assertTrue("$path expected array, got $actual", actual is JSONArray)
                assertEquals("$path length", expected.length(), (actual as JSONArray).length())
                for (index in 0 until expected.length()) {
                    assertJsonEquivalent(expected.get(index), actual.get(index), "$path[$index]")
                }
            }
            is Number -> {
                assertTrue("$path expected number, got $actual", actual is Number)
                assertEquals("$path value", expected.toDouble(), (actual as Number).toDouble(), 0.0)
            }
            else -> assertEquals("$path value", expected, actual)
        }
    }

    private fun assertRequestVector(name: String, check: (DeviceHistorySync.SyncRequest, JSONObject) -> Unit) {
        val example = vector(name)
        val expected = example.getJSONObject("request")
        val decoded = DeviceHistorySync.decodeRequest(expected.toString().encodeToByteArray())
        check(decoded, expected)
        // The re-encoded request must be semantically identical (wire-stable).
        val reencoded = DeviceHistorySync.encodeRequest(decoded)
        assertJsonEquivalent(expected, JSONObject(reencoded.decodeToString()), name)
    }

    private fun assertReplyVector(name: String, check: (DeviceHistorySync.SyncReply, JSONObject) -> Unit) {
        val example = vector(name)
        val expected = example.getJSONObject("reply")
        val decoded = DeviceHistorySync.decodeReply(expected.toString().encodeToByteArray())
        check(decoded, expected)
        val reencoded = DeviceHistorySync.encodeReply(decoded)
        assertJsonEquivalent(expected, JSONObject(reencoded.decodeToString()), name)
    }

    @Test
    fun oldPeerOffersKeepCopyOnlyWorkspaceSync() = assertReplyVector("old-peer-offers") { reply, _ ->
        // Absent capability keys keep the original v1 copy-only exchange.
        assertNull(reply.historyPages)
        assertNull(reply.attachmentTransfer)
        assertFalse(DeviceHistorySync.validatedAttachmentTransfer(reply.attachmentTransfer))
        val offer = reply.offers!!.single()
        assertEquals(UUID.fromString("10000000-0000-0000-0000-000000000001"), offer.id)
        assertEquals("Legacy fixture", offer.title)
        assertTrue(offer.workspaceFiles)
        assertNull(offer.workspaceSyncVersion)
        assertNull(offer.attachmentTransfer)
        DeviceHistorySync.validatedOffers(reply.offers)
    }

    @Test
    fun capabilityOffersAdvertiseOnlyRealCapabilities() = assertReplyVector("capability-offers") { reply, _ ->
        assertTrue(reply.historyPages == true)
        assertTrue(DeviceHistorySync.validatedAttachmentTransfer(reply.attachmentTransfer))
        val offer = reply.offers!!.single()
        assertTrue(offer.workspaceFiles)
        assertEquals(2, offer.workspaceSyncVersion)
        assertTrue(offer.attachmentTransfer == true)
        DeviceHistorySync.validatedOffers(reply.offers)
    }

    @Test
    fun v1ArchiveDescriptorPrepareUsesLegacyOperation() = assertRequestVector("v1-archive-descriptor") { request, _ ->
        assertEquals(DeviceHistorySync.Operation.PREPARE, request.operation)
        assertEquals(UUID.fromString("10000000-0000-0000-0000-000000000001"), request.taskID)
        assertNull(request.historyVersion)
        assertNull(request.after)
        assertNull(request.through)
    }

    @Test
    fun v2FinalPagePinsHistoryVersionAndCursor() = assertRequestVector("v2-final-page") { request, _ ->
        assertEquals(DeviceHistorySync.Operation.PREPARE_PAGE, request.operation)
        assertEquals(2, request.historyVersion)
        assertNull(request.after)
        assertNull(request.through)
        assertNull(request.offset)
    }

    @Test
    fun v2FinalPageReplyCarriesCursorAndBounds() = assertReplyVector("v2-final-page") { reply, _ ->
        assertEquals(1000, reply.size)
        assertEquals("29a54ea96fc35e0429cf0d33fa5808adff7a44df8017b7f5cea8b095167dc1f4", reply.digest)
        assertEquals("synthetic-cursor-final", reply.nextCursor)
        assertEquals(2L, reply.through)
        assertFalse(reply.hasMore!!)
    }

    @Test
    fun attachmentFileRequestBindsTaskAttachmentOffsetCount() = assertRequestVector("attachment-file") { request, _ ->
        assertEquals(DeviceHistorySync.Operation.ATTACHMENT_FILE, request.operation)
        assertEquals(UUID.fromString("40000000-0000-0000-0000-000000000001"), request.attachmentID)
        assertEquals(0L, request.offset)
        assertEquals(13, request.count)
    }

    @Test
    fun attachmentFileReplyCarriesExactBytes() = assertReplyVector("attachment-file") { reply, _ ->
        assertArrayEquals("Floe fixture\n".encodeToByteArray(), reply.bytes)
    }

    @Test
    fun revokedAttachmentAndChunkReportNotShared() {
        for (name in listOf("attachment-revoked", "v2-archive-chunk-revoked")) {
            val example = vector(name)
            try {
                DeviceHistorySync.decodeReply(example.getJSONObject("reply").toString().encodeToByteArray())
                fail("$name must fail with notShared")
            } catch (failure: DeviceHistorySyncException) {
                assertEquals(DeviceHistorySyncError.NOT_SHARED, failure.error)
            }
        }
    }

    @Test
    fun copyOnlyConfirmationKeepsEmptyReceipt() = assertRequestVector("copy-only-confirmation") { request, _ ->
        assertEquals(DeviceHistorySync.Operation.CONFIRM_WORKSPACE, request.operation)
        assertEquals(listOf(0), request.indexes)
        assertTrue(request.removals.isNullOrEmpty())
        assertTrue(request.renames.isNullOrEmpty())
    }

    @Test
    fun v2RenameDeleteReceiptRoundTrips() = assertRequestVector("v2-rename-delete-receipt") { request, _ ->
        assertEquals(DeviceHistorySync.Operation.CONFIRM_WORKSPACE, request.operation)
        assertEquals(emptyList<Int>(), request.indexes)
        assertEquals(listOf("notes/retired.txt"), request.removals)
        assertEquals(
            listOf(DeviceWorkspaceMove("notes/before.txt", "notes/after.txt",
                "9abefdaaaf6c45aeb85d9ee9ef5146b216b70bf4fa88baf9777fa4ce871890bd")),
            request.renames,
        )
    }

    @Test
    fun copyOnlyRejectsV2ReceiptWithInvalidResponse() {
        val example = vector("copy-only-rejects-v2-receipt")
        try {
            DeviceHistorySync.decodeReply(example.getJSONObject("reply").toString().encodeToByteArray())
            fail("copy-only rejection must surface as invalidResponse")
        } catch (failure: DeviceHistorySyncException) {
            assertEquals(DeviceHistorySyncError.INVALID_RESPONSE, failure.error)
        }
        // The request itself still decodes so a copy-only sender can log it.
        val request = DeviceHistorySync.decodeRequest(example.getJSONObject("request").toString().encodeToByteArray())
        assertEquals(listOf("notes/retired.txt"), request.removals)
        assertEquals(1, request.renames!!.size)
    }

    @Test
    fun archiveFixturesBindToManifestDigestsAndSizes() {
        val v1 = fixtureBytes("legacy-v1-archive.json")
        assertEquals(332, v1.size)
        assertEquals("828a543c06deeb021cec0238e3d797c1ac965559a9600a06564fea3ac0c87628", sha256(v1))
        val v2 = fixtureBytes("typed-v2-archive.json")
        assertEquals(1000, v2.size)
        assertEquals("29a54ea96fc35e0429cf0d33fa5808adff7a44df8017b7f5cea8b095167dc1f4", sha256(v2))
        val attachment = fixtureBytes("attachment-bytes.txt")
        assertEquals(13, attachment.size)
        assertEquals("9abefdaaaf6c45aeb85d9ee9ef5146b216b70bf4fa88baf9777fa4ce871890bd", sha256(attachment))
    }

    @Test
    fun disabledCapabilitiesStayOmittedOnTheWire() {
        val plain = DeviceHistorySync.encodeReply(
            DeviceHistorySync.SyncReply(
                offers = listOf(DeviceHistoryOffer(UUID.randomUUID(), "Only text")),
            ),
        )
        val json = JSONObject(plain.decodeToString())
        assertFalse(json.has("historyPages"))
        assertFalse(json.has("attachmentTransfer"))
        assertFalse(json.getJSONArray("offers").getJSONObject(0).has("workspaceFiles"))
        assertFalse(json.getJSONArray("offers").getJSONObject(0).has("workspaceSyncVersion"))
        assertFalse(json.getJSONArray("offers").getJSONObject(0).has("attachmentTransfer"))

        val request = DeviceHistorySync.encodeRequest(
            DeviceHistorySync.SyncRequest(DeviceHistorySync.Operation.PREPARE, taskID = UUID.randomUUID()),
        )
        val requestJson = JSONObject(request.decodeToString())
        assertFalse(requestJson.has("historyVersion"))
        assertFalse(requestJson.has("attachmentID"))
        assertFalse(requestJson.has("removals"))
        assertFalse(requestJson.has("renames"))
    }

    @Test
    fun catalogValidationRejectsUnknownCapabilityValues() {
        val badVersion = """{"version":1,"offers":[{"id":"10000000-0000-0000-0000-000000000001","title":"T","workspaceFiles":true,"workspaceSyncVersion":3}]}"""
        try {
            DeviceHistorySync.validatedOffers(
                DeviceHistorySync.decodeReply(badVersion.encodeToByteArray()).offers,
            )
            fail("workspaceSyncVersion=3 must be rejected")
        } catch (failure: DeviceHistorySyncException) {
            assertEquals(DeviceHistorySyncError.INVALID_RESPONSE, failure.error)
        }
        try {
            DeviceHistorySync.validatedAttachmentTransfer(false)
            fail("explicit attachmentTransfer=false must be rejected")
        } catch (failure: DeviceHistorySyncException) {
            assertEquals(DeviceHistorySyncError.INVALID_RESPONSE, failure.error)
        }
    }

    @Test
    fun malformedRequestsFailDecode() {
        fun assertRejected(body: String) {
            try {
                DeviceHistorySync.decodeRequest(body.encodeToByteArray())
                fail("request must be rejected: $body")
            } catch (failure: DeviceHistorySync.RequestDecodeException) {
                // expected
            }
        }
        assertRejected("""{"version":1,"operation":"chunk","taskID":"10000000-0000-0000-0000-000000000001","offset":1.5}""")
        assertRejected("""{"version":1,"operation":"preparePage","taskID":"10000000-0000-0000-0000-000000000001","through":"2"}""")
        assertRejected("""{"operation":"offers"}""")
        assertRejected("""{"version":1,"operation":"preparePage","taskID":"10000000-0000-0000-0000-000000000001","historyVersion":"2"}""")
        assertRejected("""{"version":1,"operation":"preparePage","taskID":"10000000-0000-0000-0000-000000000001","attachmentID":"nope"}""")
        assertRejected("""{"version":1,"operation":"confirmWorkspace","taskID":"10000000-0000-0000-0000-000000000001","renames":[{"from":"a","to":"b"}]}""")
        assertRejected("""{"version":1,"operation":"bogus","taskID":"10000000-0000-0000-0000-000000000001"}""")
    }

    @Test
    fun malformedRepliesFailDecode() {
        fun assertRejected(body: String, expected: DeviceHistorySyncError = DeviceHistorySyncError.INVALID_RESPONSE) {
            try {
                DeviceHistorySync.decodeReply(body.encodeToByteArray())
                fail("reply must be rejected: $body")
            } catch (failure: DeviceHistorySyncException) {
                assertEquals(expected, failure.error)
            }
        }
        assertRejected("""{"version":1,"offers":[{"id":"10000000-0000-0000-0000-000000000001","title":"T","workspaceSyncVersion":"2"}]}""")
        assertRejected("""{"version":1,"size":"13"}""")
        assertRejected("""{"version":2,"offers":[]}""", DeviceHistorySyncError.UNSUPPORTED_VERSION)
    }
}
