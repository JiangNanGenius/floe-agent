/**
 * Download state is deliberately SEPARATE from install state: stopping a
 * download never claims that an already-committed install was cancelled, and
 * a committed PackageInstaller session keeps its own system-owned lifecycle.
 */
internal sealed interface AppDownloadState {
    data object Idle : AppDownloadState
    data class InProgress(
        val versionName: String,
        val received: Long,
        val total: Long,
        val mode: DownloadMode = DownloadMode.FULL,
    ) : AppDownloadState
    data class Verifying(val versionName: String) : AppDownloadState

    /** The verified patch is being reconstructed into the exact target APK. */
    data class Applying(val versionName: String) : AppDownloadState
    data class Ready(
        val versionName: String,
        val fileName: String,
        val sha256: String,
        val mode: DownloadMode = DownloadMode.FULL,
    ) : AppDownloadState
    data class Paused(val versionName: String, val received: Long, val total: Long) : AppDownloadState
    data class Failed(
        val versionName: String,
        val kind: DownloadFailure,
        val resumable: Boolean,
    ) : AppDownloadState

    /**
     * A delta was attempted and refused/failed AFTER the user chose to update.
     * The generated bytes are already deleted; the UI must offer the full APK
     * as an explicit next step instead of silently downloading 400+ MB.
     */
    data class DeltaFallback(
        val versionName: String,
        val reason: DeltaFallbackReason,
        val fullBytes: Long,
    ) : AppDownloadState
}

internal enum class DownloadMode { FULL, DELTA }

internal enum class DeltaFallbackReason {
    NOT_OFFERED,
    BASE_MISMATCH,
    PATCH_UNAVAILABLE,
    PATCH_CORRUPT,
    APPLY_FAILED,
    OUTPUT_INVALID,
    DISK,
}

internal enum class DownloadFailure {
    NETWORK,
    DISK,
    SIZE_BUDGET,
    NO_CHECKSUM,
    CHECKSUM_MISMATCH,
    APK_IDENTITY,
    INVALID_ASSET,
}

/** Persisted staging record: enough to resume or verify after process death. */
internal data class DownloadMeta(
    val tag: String,
    val versionName: String,
    val fileName: String,
    val apkUrl: String,
    val checksumsUrl: String,
    val expectedSha256: String,
    val totalBytes: Long,
    val receivedBytes: Long,
    val etag: String?,
    val completed: Boolean,
    /** FULL for the release APK; DELTA when the target was reconstructed. */
    val mode: DownloadMode = DownloadMode.FULL,
    val deltaBaseSha256: String? = null,
    val deltaPatchName: String? = null,
    val deltaPatchSha256: String? = null,
    val deltaPatchBytes: Long = 0L,
) {
    fun toJson(): String = buildJsonObject {
        put("tag", tag)
        put("versionName", versionName)
        put("fileName", fileName)
        put("apkUrl", apkUrl)
        put("checksumsUrl", checksumsUrl)
        put("expectedSha256", expectedSha256)
        put("totalBytes", totalBytes)
        put("receivedBytes", receivedBytes)
        put("etag", etag ?: "")
        put("completed", completed)
        put("mode", mode.name)
        if (mode == DownloadMode.DELTA) {
            put("deltaBaseSha256", deltaBaseSha256 ?: "")
            put("deltaPatchName", deltaPatchName ?: "")
            put("deltaPatchSha256", deltaPatchSha256 ?: "")
            put("deltaPatchBytes", deltaPatchBytes)
        }
    }.toString()

    companion object {
        fun fromJson(text: String?): DownloadMeta? {
            if (text.isNullOrBlank()) return null
            val obj = runCatching { Json.parseToJsonElement(text) as? JsonObject }.getOrNull() ?: return null
            fun string(key: String): String? =
                (obj[key] as? JsonPrimitive)?.takeIf { it.isString }?.content
            fun long(key: String): Long? = (obj[key] as? JsonPrimitive)?.longOrNull
            val tag = string("tag") ?: return null
            val versionName = string("versionName") ?: return null
            val fileName = string("fileName") ?: return null
            val apkUrl = string("apkUrl") ?: return null
            val checksumsUrl = string("checksumsUrl") ?: return null
            val expected = string("expectedSha256") ?: return null
            if (expected.isNotEmpty() && !expected.matches(Regex("[0-9a-f]{64}"))) return null
            if (fileName.isEmpty() || fileName.contains('/') || fileName.contains('\\')) return null
            if (!apkUrl.startsWith("https://") || !checksumsUrl.startsWith("https://")) return null
            val total = long("totalBytes") ?: -1L
            val received = long("receivedBytes") ?: 0L
            if (total != -1L && (total < 0L || total > AndroidReleaseFeed.MAX_APK_BYTES)) return null
            if (received < 0L || (total > 0L && received > total)) return null
            val etag = string("etag")?.takeIf { it.isNotEmpty() }
            val completed = (obj["completed"] as? JsonPrimitive)?.booleanOrNull ?: false
            val mode = when (string("mode")) {
                "DELTA" -> DownloadMode.DELTA
                else -> DownloadMode.FULL
            }
            val baseSha = string("deltaBaseSha256")?.takeIf { it.matches(Regex("[0-9a-f]{64}")) }
            val patchName = string("deltaPatchName")
                ?.takeIf { UpdateDeltaFormat.isSafeAssetName(it) }
            val patchSha = string("deltaPatchSha256")?.takeIf { it.matches(Regex("[0-9a-f]{64}")) }
            val patchBytes = long("deltaPatchBytes") ?: 0L
            if (mode == DownloadMode.DELTA) {
                if (baseSha == null || patchName == null || patchSha == null ||
                    patchBytes !in 1..UpdateDeltaFormat.MAX_PATCH_BYTES
                ) {
                    return null
                }
            }
            return DownloadMeta(
                tag = tag,
                versionName = versionName,
                fileName = fileName,
                apkUrl = apkUrl,
                checksumsUrl = checksumsUrl,
                expectedSha256 = expected,
                totalBytes = total,
                receivedBytes = received,
                etag = etag,
                completed = completed,
                mode = mode,
                deltaBaseSha256 = baseSha,
                deltaPatchName = patchName,
                deltaPatchSha256 = patchSha,
                deltaPatchBytes = patchBytes,
            )
        }
    }
}

internal sealed interface ResumePlan {
    data class AppendFrom(val offset: Long) : ResumePlan
    data object Restart : ResumePlan
}

/**
 * Resume decision shared by the downloader and its tests.
 *
 * Appending staged bytes is allowed ONLY for a real HTTP 206 partial response
 * whose `Content-Range` starts at the exact staged offset, whose total still
 * matches, and whose `ETag` equals the staged artifact's `ETag`. Anything
 * else restarts from byte zero — a changed artifact must never be extended
 * with bytes of the previous one.
 */
internal object DownloadPlanning {
    fun plan(
        stagedBytes: Long,
        stagedEtag: String?,
        httpStatus: Int,
        contentRangeStart: Long?,
        contentRangeTotal: Long?,
        responseEtag: String?,
        expectedTotal: Long,
    ): ResumePlan {
        if (stagedBytes <= 0L) return ResumePlan.Restart
        if (httpStatus != 206) return ResumePlan.Restart
        if (contentRangeStart == null || contentRangeStart != stagedBytes) return ResumePlan.Restart
        if (contentRangeTotal != null && expectedTotal > 0L && contentRangeTotal != expectedTotal) {
            return ResumePlan.Restart
        }
        // No stable validator means the staged prefix cannot be attributed to
        // the artifact being served now: restart rather than mix bytes.
        if (stagedEtag.isNullOrEmpty() || responseEtag.isNullOrEmpty()) return ResumePlan.Restart
        if (stagedEtag != responseEtag) return ResumePlan.Restart
        return ResumePlan.AppendFrom(stagedBytes)
    }
}

/**
 * App-owned download engine.
 *
 * Writer ownership (Main critical review, 2026-10-29): exactly ONE download
 * writer may own the staging files at a time. `start`/`resume`/`discard` are
 * serialized by [transitions]: an old writer is signalled, its job is
 * cancelled AND joined (so its blocking read/stream close actually completed
 * and its `use` blocks closed the stream) before any file is deleted or a new
 * writer starts. Each writer carries its OWN cancellation flag and generation,
 * and every state/store write is identity-fenced to that writer, so a stale
 * `finally` or a late progress publish can never clear/overwrite a newer
 * writer. Cancellation is checked after every blocking read and before every
 * publish/persist/rename.
 */
internal class UpdateDownloader(
    private val scope: CoroutineScope,
    private val transport: DownloadTransport,
    private val store: UpdateStore,
    private val stagingDir: File,
    private val validate: (File) -> DownloadFailure?,
    /**
     * Restore-only settlement proof: true when the verified staging bytes are
     * exactly the app that is already installed. A downloaded target that a
     * completed install consumed is retired, never re-admitted as a new
     * update (which would reject VERSION_NOT_HIGHER as a false mismatch).
     */
    private val settledTarget: (File) -> Boolean = { false },
    /** Installed-base facts for the delta path; null disables deltas. */
    private val deltaBaseProvider: InstalledBaseProvider? = null,
    private val deltaApplier: FloePatchApplier = FloePatchApplier(),
    private val nowMillis: () -> Long = System::currentTimeMillis,
) {
    /** In-memory outcome of one delta attempt inside the owned writer. */
    private enum class DeltaOutcome { PROCEED_TO_FULL, FINISHED }
    private val mutable = MutableStateFlow<AppDownloadState>(AppDownloadState.Idle)
    val state: StateFlow<AppDownloadState> = mutable.asStateFlow()

    /** Serializes start/resume/discard transitions (cancel + join + delete). */
    private val transitions = Mutex()

    /** Guards the current writer identity and every state/store write. */
    private val writerLock = Any()
    private var writer: Writer? = null
    private val generations = AtomicLong(0)

    private class Writer(val generation: Long, val cancelled: AtomicBoolean) {
        lateinit var job: Job
    }

    /** Process-restart reconciliation of a staged/incomplete download. */
    fun reconcile() {
        synchronized(writerLock) {
            if (writer != null || mutable.value !is AppDownloadState.Idle) return
        }
        val meta = DownloadMeta.fromJson(store.pendingDownloadJson)
        if (meta == null) {
            cleanupDeltaLeftovers()
            return
        }
        // A delta that did not complete is never resumed: its patch and partial
        // target are deleted so a restarted process cannot mistake a truncated
        // reconstruction for a verified update. The user simply starts again.
        if (meta.mode == DownloadMode.DELTA && !meta.completed) {
            deltaPatchFile(meta).delete()
            deltaTargetFile(meta).delete()
            store.pendingDownloadJson = null
            cleanupDeltaLeftovers()
            return
        }
        val apk = apkFile(meta)
        if (meta.completed && apk.isFile && (meta.totalBytes <= 0L || apk.length() == meta.totalBytes)) {
            scope.launch(Dispatchers.IO) { transitions.withLock { verifyCompleted(meta, apk) } }
            return
        }
        val part = partFile(meta)
        if (part.isFile && part.length() > 0L) {
            synchronized(writerLock) {
                if (writer == null) {
                    mutable.value = AppDownloadState.Paused(meta.versionName, part.length(), meta.totalBytes)
                }
            }
        } else {
            store.pendingDownloadJson = null
        }
    }

    private fun cleanupDeltaLeftovers() {
        runCatching {
            stagingDir.listFiles()?.forEach { file ->
                if (file.name.endsWith(".delta.part") || file.name.endsWith(".target.partial")) {
                    file.delete()
                }
            }
        }
    }

    /** Starts (or resumes) the download for [release]. Never runs twice at once. */
    fun start(release: AndroidRelease, allowDelta: Boolean = true) {
        val fileName = release.apk.name
        if (fileName.contains('/') || fileName.contains('\\')) {
            mutable.value = AppDownloadState.Failed(release.version.toString(), DownloadFailure.INVALID_ASSET, false)
            return
        }
        scope.launch(Dispatchers.IO) {
            transitions.withLock {
                val current = mutable.value
                if (current is AppDownloadState.Ready && current.fileName == fileName) {
                    val ready = apkFile(fileName)
                    if (ready.isFile && ready.length() > 0L) return@withLock
                }
                val runningVersion = when (current) {
                    is AppDownloadState.InProgress -> current.versionName
                    is AppDownloadState.Verifying -> current.versionName
                    is AppDownloadState.Applying -> current.versionName
                    else -> null
                }
                if (runningVersion == release.version.toString()) {
                    // Controller.startDownload already began this exact
                    // writer; the service action must not cancel and restart it.
                    return@withLock
                }
                cancelAndJoinWriter()
                cleanupDeltaLeftovers()
                val persisted = DownloadMeta.fromJson(store.pendingDownloadJson)
                val reusable = persisted != null &&
                    persisted.fileName == fileName &&
                    persisted.apkUrl == release.apk.downloadUrl &&
                    !persisted.completed
                val meta = if (reusable && persisted != null) {
                    persisted
                } else {
                    DownloadMeta(
                        tag = release.tag,
                        versionName = release.version.toString(),
                        fileName = fileName,
                        apkUrl = release.apk.downloadUrl,
                        checksumsUrl = release.checksums.downloadUrl,
                        expectedSha256 = "",
                        totalBytes = release.apk.sizeBytes,
                        receivedBytes = 0L,
                        etag = null,
                        completed = false,
                    )
                }
                beginWriter(meta, if (allowDelta) release else null)
            }
        }
    }

    /**
     * Explicit fallback choice: download the full APK even though a delta was
     * offered/attempted for this release. Stale delta bytes are removed first.
     */
    fun startFull(release: AndroidRelease) {
        start(release, allowDelta = false)
    }

    /** Resumes a paused/incomplete download from persisted metadata. */
    fun resume() {
        scope.launch(Dispatchers.IO) {
            transitions.withLock {
                val active = mutable.value
                if (active is AppDownloadState.InProgress ||
                    active is AppDownloadState.Verifying ||
                    active is AppDownloadState.Applying
                ) {
                    return@withLock
                }
                val meta = DownloadMeta.fromJson(store.pendingDownloadJson) ?: return@withLock
                cancelAndJoinWriter()
                if (meta.completed) {
                    val apk = apkFile(meta)
                    if (apk.isFile) {
                        verifyCompleted(meta, apk)
                        return@withLock
                    }
                }
                beginWriter(meta)
            }
        }
    }

    /** Signals the current writer; its own catch publishes the paused state. */
    fun cancel() {
        val current = synchronized(writerLock) { writer }
        if (current == null) {
            publishPausedNoWriter()
            return
        }
        current.cancelled.set(true)
        current.job.cancel()
    }

    /** Explicit "delete the downloaded package" action. */
    fun discard() {
        scope.launch(Dispatchers.IO) {
            transitions.withLock {
                // The old writer's blocking read/stream close/completion must
                // finish BEFORE any staging byte is deleted.
                cancelAndJoinWriter()
                DownloadMeta.fromJson(store.pendingDownloadJson)?.let { meta ->
                    partFile(meta).delete()
                    apkFile(meta).delete()
                }
                stagingDir.listFiles()?.forEach { file -> file.delete() }
                store.pendingDownloadJson = null
                synchronized(writerLock) {
                    if (writer == null) mutable.value = AppDownloadState.Idle
                }
            }
        }
    }

    fun readyFile(): File? {
        val ready = mutable.value as? AppDownloadState.Ready ?: return null
        val file = File(stagingDir, ready.fileName)
        return file.takeIf { it.isFile }
    }

    /**
     * Cancels and JOINS the current writer. Clears the identity first so the
     * old writer's late catch/finally cannot publish into the next owner.
     */
    private suspend fun cancelAndJoinWriter() {
        val previous = synchronized(writerLock) {
            val current = writer
            writer = null
            current
        } ?: return
        previous.cancelled.set(true)
        previous.job.cancel()
        previous.job.join()
    }

    private fun beginWriter(initial: DownloadMeta, release: AndroidRelease? = null) {
        prepareStaging(initial)
        val generation = generations.incrementAndGet()
        val owner = Writer(generation, AtomicBoolean(false))
        val job = scope.launch(Dispatchers.IO, start = CoroutineStart.LAZY) {
            runWriter(owner, initial, release)
        }
        owner.job = job
        synchronized(writerLock) { writer = owner }
        job.start()
    }

    private suspend fun runWriter(owner: Writer, initial: DownloadMeta, release: AndroidRelease?) {
        try {
            stageAndDownload(owner, initial, release)
        } catch (cancellation: CancellationException) {
            publishPaused(owner)
            throw cancellation
        } catch (failure: StageFailure) {
            publish(owner, AppDownloadState.Failed(
                versionName = failure.versionName,
                kind = failure.kind,
                resumable = failure.resumable,
            ))
        } catch (failure: Exception) {
            val versionName = synchronized(writerLock) {
                if (writer === owner) {
                    DownloadMeta.fromJson(store.pendingDownloadJson)?.versionName ?: ""
                } else {
                    ""
                }
            }
            if (!owner.cancelled.get()) {
                publish(owner, AppDownloadState.Failed(versionName, DownloadFailure.NETWORK, true))
            }
        } finally {
            synchronized(writerLock) {
                if (writer === owner) writer = null
            }
        }
    }

    private fun checkCancelled(owner: Writer) {
        if (owner.cancelled.get()) throw CancellationException("download-cancelled")
    }

    private fun publish(owner: Writer, state: AppDownloadState) {
        synchronized(writerLock) {
            if (writer === owner) mutable.value = state
        }
    }

    private fun persist(owner: Writer, meta: DownloadMeta) {
        synchronized(writerLock) {
            if (writer === owner) store.pendingDownloadJson = meta.toJson()
        }
    }

    private suspend fun stageAndDownload(owner: Writer, initial: DownloadMeta, release: AndroidRelease?) {
        checkCancelled(owner)
        var working = initial
        prepareStaging(working)
        checkCancelled(owner)
        checkDisk(working)
        // One authoritative checksum map for both paths: the full APK's hash
        // and (when present) the release-bound manifest/patch hashes. A resume
        // that already carries its expected APK hash only re-fetches when the
        // delta manifest must also be admitted.
        val needsChecksums = (release != null && release.delta != null) || working.expectedSha256.isEmpty()
        val checksums = if (needsChecksums) fetchChecksums(owner, working) else emptyMap()
        val expected = working.expectedSha256.ifEmpty {
            checksums[working.fileName]
                ?: throw StageFailure(working.versionName, DownloadFailure.NO_CHECKSUM, resumable = false)
        }
        working = working.copy(expectedSha256 = expected)
        checkCancelled(owner)
        if (release != null && UpdateConfig.DELTA_ENABLED) {
            when (tryDelta(owner, working, release, checksums)) {
                DeltaOutcome.PROCEED_TO_FULL -> Unit
                DeltaOutcome.FINISHED -> return
            }
        }
        downloadFull(owner, working)
    }

    /** The original, unchanged full-APK download path. */
    private suspend fun downloadFull(owner: Writer, initial: DownloadMeta) {
        var working = initial
        val part = partFile(working)
        var existing = if (part.isFile) part.length() else 0L
        if (working.totalBytes > 0L && existing > working.totalBytes) {
            part.delete()
            existing = 0L
        }

        var response = transport.open(working.apkUrl, existing.takeIf { it > 0L }, working.etag)
        checkCancelled(owner)
        var plan = DownloadPlanning.plan(
            stagedBytes = existing,
            stagedEtag = working.etag,
            httpStatus = response.code,
            contentRangeStart = response.contentRangeStart,
            contentRangeTotal = response.contentRangeTotal,
            responseEtag = response.etag,
            expectedTotal = working.totalBytes,
        )
        if (plan is ResumePlan.Restart && existing > 0L) {
            // The server answered a ranged request that cannot be appended;
            // drop the staged prefix and issue a fresh full request.
            runCatching { response.stream.close() }
            part.delete()
            existing = 0L
            response = transport.open(working.apkUrl, null, null)
            checkCancelled(owner)
            plan = ResumePlan.Restart
        }
        val startOffset = when (plan) {
            is ResumePlan.AppendFrom -> plan.offset
            ResumePlan.Restart -> 0L
        }
        val total = when {
            working.totalBytes > 0L -> working.totalBytes
            response.code == 206 -> response.contentRangeTotal ?: -1L
            response.contentLength > 0L -> response.contentLength
            else -> -1L
        }
        working = working.copy(
            receivedBytes = startOffset,
            etag = response.etag ?: working.etag,
            totalBytes = total,
        )
        checkCancelled(owner)
        persist(owner, working)
        publish(owner, AppDownloadState.InProgress(working.versionName, startOffset, total))

        var received = startOffset
        var lastPublishedAt = 0L
        val versionName = working.versionName
        FileOutputStream(part, startOffset > 0L).use { output ->
            response.stream.use { input ->
                val buffer = ByteArray(256 * 1024)
                while (true) {
                    checkCancelled(owner)
                    val count = input.read(buffer)
                    // The read may have blocked for a long time: never write,
                    // publish, persist or rename after a cancellation.
                    checkCancelled(owner)
                    if (count < 0) break
                    received += count
                    if (received > AndroidReleaseFeed.MAX_APK_BYTES) {
                        throw StageFailure(versionName, DownloadFailure.SIZE_BUDGET, resumable = false)
                    }
                    output.write(buffer, 0, count)
                    checkCancelled(owner)
                    val now = nowMillis()
                    if (now - lastPublishedAt >= PROGRESS_INTERVAL_MS) {
                        lastPublishedAt = now
                        publish(owner, AppDownloadState.InProgress(versionName, received, total))
                    }
                }
            }
            output.fd.sync()
        }
        checkCancelled(owner)

        val completedMeta = working.copy(receivedBytes = received)
        if (total > 0L && received != total) {
            persist(owner, completedMeta)
            throw StageFailure(versionName, DownloadFailure.NETWORK, resumable = true)
        }

        publish(owner, AppDownloadState.Verifying(versionName))
        val actual = sha256(owner, part)
        checkCancelled(owner)
        if (!actual.equals(working.expectedSha256, ignoreCase = true)) {
            part.delete()
            synchronized(writerLock) { if (writer === owner) store.pendingDownloadJson = null }
            throw StageFailure(versionName, DownloadFailure.CHECKSUM_MISMATCH, resumable = false)
        }
        val apk = apkFile(working)
        if (apk.exists()) apk.delete()
        checkCancelled(owner)
        if (!part.renameTo(apk)) {
            throw StageFailure(versionName, DownloadFailure.DISK, resumable = true)
        }
        checkCancelled(owner)
        persist(owner, completedMeta.copy(completed = true))
        validate(apk)?.let { failure ->
            apk.delete()
            synchronized(writerLock) { if (writer === owner) store.pendingDownloadJson = null }
            throw StageFailure(versionName, failure, resumable = false)
        }
        publish(owner, AppDownloadState.Ready(versionName, working.fileName, actual))
    }

    /**
     * Delta attempt inside the single owned writer.
     *
     * A delta is only attempted when the release carries a manifest bound by
     * SHA256SUMS and the installed base APK's exact bytes/version/package/
     * signer set match it. Every failure that happens AFTER that decision
     * deletes all generated bytes and publishes [AppDownloadState.DeltaFallback]
     * so the user can choose the full APK; nothing is silently retried and no
     * partial reconstruction is ever kept.
     */
    private suspend fun tryDelta(
        owner: Writer,
        working: DownloadMeta,
        release: AndroidRelease,
        checksums: Map<String, String>,
    ): DeltaOutcome {
        val provider = deltaBaseProvider ?: return DeltaOutcome.PROCEED_TO_FULL
        val manifestAsset = release.delta ?: return DeltaOutcome.PROCEED_TO_FULL
        val installed = provider.read() ?: return DeltaOutcome.PROCEED_TO_FULL
        val manifestText = try {
            val response = transport.open(manifestAsset.downloadUrl, null, null)
            checkCancelled(owner)
            response.stream.use {
                readBoundedBytes(owner, it, UpdateDeltaFormat.MAX_MANIFEST_BYTES)
            }.toString(Charsets.UTF_8)
        } catch (cancellation: CancellationException) {
            throw cancellation
        } catch (failure: StageFailure) {
            throw failure
        } catch (failure: Exception) {
            return DeltaOutcome.PROCEED_TO_FULL
        }
        checkCancelled(owner)
        val manifestChecksum = checksums[manifestAsset.name] ?: return DeltaOutcome.PROCEED_TO_FULL
        if (!sha256Bytes(manifestText.toByteArray(Charsets.UTF_8)).equals(manifestChecksum, ignoreCase = true)) {
            // The manifest is not the bytes the release checksum binds: ignore
            // the delta entirely rather than reasoning about an unbound file.
            return DeltaOutcome.PROCEED_TO_FULL
        }
        val baseFile = installed.apkFile ?: return DeltaOutcome.PROCEED_TO_FULL
        val baseSha = try {
            sha256(owner, baseFile)
        } catch (cancellation: CancellationException) {
            throw cancellation
        } catch (failure: Exception) {
            return DeltaOutcome.PROCEED_TO_FULL
        }
        checkCancelled(owner)
        val decision = UpdateDeltaPolicy.decide(
            enabled = true,
            release = release,
            checksums = checksums,
            manifestText = manifestText,
            installed = installed,
            installedApkSha256 = baseSha,
        )
        if (decision !is DeltaDecision.Use) return DeltaOutcome.PROCEED_TO_FULL
        val manifest = decision.manifest

        // Peak requirement: patch + reconstructed target + install headroom.
        val required = manifest.patch.sizeBytes + manifest.target.sizeBytes +
            UpdateConfig.DISK_HEADROOM_BYTES
        val usable = stagingDir.usableSpace
        if (usable in 1L until required) {
            publish(owner, AppDownloadState.DeltaFallback(
                versionName = working.versionName,
                reason = DeltaFallbackReason.DISK,
                fullBytes = manifest.target.sizeBytes,
            ))
            return DeltaOutcome.FINISHED
        }

        val patch = deltaPatchFile(working)
        patch.delete()
        val versionName = working.versionName
        try {
            downloadPatch(owner, versionName, decision.patchAsset, manifest.patch.sizeBytes, patch)
        } catch (cancellation: CancellationException) {
            patch.delete()
            throw cancellation
        } catch (failure: DeltaAttempt) {
            patch.delete()
            publish(owner, AppDownloadState.DeltaFallback(versionName, failure.reason, manifest.target.sizeBytes))
            return DeltaOutcome.FINISHED
        }
        checkCancelled(owner)

        val patchSha = sha256(owner, patch)
        if (!patchSha.equals(manifest.patch.sha256, ignoreCase = true) ||
            patch.length() != manifest.patch.sizeBytes
        ) {
            patch.delete()
            publish(owner, AppDownloadState.DeltaFallback(
                versionName = versionName,
                reason = DeltaFallbackReason.PATCH_CORRUPT,
                fullBytes = manifest.target.sizeBytes,
            ))
            return DeltaOutcome.FINISHED
        }

        publish(owner, AppDownloadState.Applying(versionName))
        val partial = deltaTargetFile(working)
        val result = deltaApplier.apply(
            base = baseFile,
            patch = patch,
            output = partial,
            manifest = manifest,
            checkCancelled = { owner.cancelled.get() },
            // The applier bounds the output to the manifest size; progress is
            // intentionally not re-published per op (the Applying state is
            // already visible and a 1 GiB fsync-bound copy needs no UI churn).
            onProgress = { },
        )
        patch.delete()
        when (result) {
            is DeltaApplyResult.Success -> Unit
            DeltaApplyResult.Cancelled -> {
                partial.delete()
                // A user cancel is not a failure: rethrow as cancellation so
                // the writer publishes the paused/idle state (never "failed").
                throw CancellationException("delta-cancelled")
            }
            is DeltaApplyResult.Failure -> {
                partial.delete()
                publish(owner, AppDownloadState.DeltaFallback(
                    versionName = versionName,
                    reason = when (result.reason) {
                        DeltaApplyFailure.PATCH_SIZE_MISMATCH,
                        DeltaApplyFailure.BAD_MAGIC,
                        DeltaApplyFailure.BAD_HEADER,
                        DeltaApplyFailure.UNSUPPORTED_FORMAT,
                        DeltaApplyFailure.BASE_MISMATCH -> DeltaFallbackReason.PATCH_UNAVAILABLE
                        else -> DeltaFallbackReason.APPLY_FAILED
                    },
                    fullBytes = manifest.target.sizeBytes,
                ))
                return DeltaOutcome.FINISHED
            }
        }
        checkCancelled(owner)
        publish(owner, AppDownloadState.Verifying(versionName))
        validate(partial)?.let {
            partial.delete()
            publish(owner, AppDownloadState.DeltaFallback(
                versionName = versionName,
                reason = DeltaFallbackReason.OUTPUT_INVALID,
                fullBytes = manifest.target.sizeBytes,
            ))
            return DeltaOutcome.FINISHED
        }
        // The reconstructed bytes already proved the release target SHA-256 in
        // the applier; the identity policy above re-proved package/version/
        // signer/ABI. Only now are they published as the ready APK.
        val target = apkFile(working)
        if (target.exists()) target.delete()
        checkCancelled(owner)
        if (!partial.renameTo(target)) {
            partial.delete()
            publish(owner, AppDownloadState.DeltaFallback(
                versionName = versionName,
                reason = DeltaFallbackReason.DISK,
                fullBytes = manifest.target.sizeBytes,
            ))
            return DeltaOutcome.FINISHED
        }
        persist(owner, working.copy(
            completed = true,
            receivedBytes = manifest.target.sizeBytes,
            totalBytes = manifest.target.sizeBytes,
            mode = DownloadMode.DELTA,
            deltaBaseSha256 = manifest.base.sha256,
            deltaPatchName = manifest.patch.assetName,
            deltaPatchSha256 = manifest.patch.sha256,
            deltaPatchBytes = manifest.patch.sizeBytes,
        ))
        publish(owner, AppDownloadState.Ready(versionName, working.fileName, manifest.target.sha256, DownloadMode.DELTA))
        return DeltaOutcome.FINISHED
    }

    private class DeltaAttempt(val reason: DeltaFallbackReason) : Exception(reason.name)

    /** Sequential patch download with a hard size bound and cancellation checks. */
    private suspend fun downloadPatch(
        owner: Writer,
        versionName: String,
        asset: ReleaseAsset,
        expectedBytes: Long,
        output: File,
    ) {
        val response = try {
            transport.open(asset.downloadUrl, null, null)
        } catch (cancellation: CancellationException) {
            throw cancellation
        } catch (failure: Exception) {
            throw DeltaAttempt(DeltaFallbackReason.PATCH_UNAVAILABLE)
        }
        checkCancelled(owner)
        var received = 0L
        var lastPublishedAt = 0L
        try {
            FileOutputStream(output, false).use { fileOutput ->
                response.stream.use { input ->
                    val buffer = ByteArray(256 * 1024)
                    while (true) {
                        checkCancelled(owner)
                        val count = input.read(buffer)
                        checkCancelled(owner)
                        if (count < 0) break
                        received += count
                        if (received > expectedBytes) {
                            throw DeltaAttempt(DeltaFallbackReason.PATCH_CORRUPT)
                        }
                        fileOutput.write(buffer, 0, count)
                        val now = nowMillis()
                        if (now - lastPublishedAt >= PROGRESS_INTERVAL_MS) {
                            lastPublishedAt = now
                            publish(owner, AppDownloadState.InProgress(
                                versionName, received, expectedBytes, DownloadMode.DELTA,
                            ))
                        }
                    }
                }
                fileOutput.fd.sync()
            }
        } catch (cancellation: CancellationException) {
            throw cancellation
        } catch (failure: DeltaAttempt) {
            throw failure
        } catch (failure: Exception) {
            throw DeltaAttempt(DeltaFallbackReason.PATCH_UNAVAILABLE)
        }
        if (received != expectedBytes) {
            throw DeltaAttempt(DeltaFallbackReason.PATCH_CORRUPT)
        }
    }

    private fun deltaPatchFile(meta: DownloadMeta): File =
        File(stagingDir, "${tagPrefix(meta)}.delta.part")

    private fun deltaTargetFile(meta: DownloadMeta): File =
        File(stagingDir, "${tagPrefix(meta)}.target.partial")

    private fun sha256Bytes(bytes: ByteArray): String =
        MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

    private fun readBoundedBytes(owner: Writer, input: InputStream, limit: Long): ByteArray {
        val buffer = java.io.ByteArrayOutputStream()
        val chunk = ByteArray(8 * 1024)
        var total = 0L
        while (true) {
            checkCancelled(owner)
            val count = input.read(chunk)
            if (count < 0) break
            total += count
            if (total > limit) throw IOException("manifest-oversized")
            buffer.write(chunk, 0, count)
        }
        return buffer.toByteArray()
    }

    /**
     * Re-verifies one persisted completed download after process restart.
     *
     * A completed install can settle while this restore is still running (the
     * install owner clears the record and deletes the staged file). Every
     * decision below is therefore fenced by [isCurrentRecord] AGAIN after the
     * slow hash/identity work: a late verdict for a record that a successful
     * install already consumed must not publish APK_IDENTITY. A settled target
     * is retired as consumed; genuinely stale or wrong bytes keep the normal
     * admission rejection.
     */
    private suspend fun verifyCompleted(meta: DownloadMeta, apk: File) {
        mutable.value = AppDownloadState.Verifying(meta.versionName)
        val actual = try {
            sha256(apk)
        } catch (cancellation: CancellationException) {
            throw cancellation
        } catch (failure: Exception) {
            // The staged bytes vanished during restore. When the record was
            // also retired, an install settled this target; otherwise the
            // completed record is unusable and a fresh download is the honest
            // recovery (never a fabricated install or an identity claim).
            if (!isCurrentRecord(meta)) {
                clearSuperseded(meta)
                return
            }
            store.pendingDownloadJson = null
            mutable.value = AppDownloadState.Idle
            return
        }
        if (!actual.equals(meta.expectedSha256, ignoreCase = true)) {
            if (!isCurrentRecord(meta)) {
                clearSuperseded(meta)
                return
            }
            apk.delete()
            store.pendingDownloadJson = null
            mutable.value = AppDownloadState.Failed(meta.versionName, DownloadFailure.CHECKSUM_MISMATCH, false)
            return
        }
        if (!isCurrentRecord(meta)) {
            clearSuperseded(meta)
            return
        }
        if (settledTarget(apk)) {
            // These verified bytes are the app that is already installed: the
            // install that consumed this download has settled. Retire only
            // this task-owned record and its exact staged file instead of
            // re-admitting the equal version as a new update.
            store.pendingDownloadJson = null
            runCatching { apk.delete() }
            clearSuperseded(meta)
            return
        }
        validate(apk)?.let { failure ->
            if (!isCurrentRecord(meta)) {
                clearSuperseded(meta)
                return
            }
            apk.delete()
            store.pendingDownloadJson = null
            mutable.value = AppDownloadState.Failed(meta.versionName, failure, false)
            return
        }
        if (!isCurrentRecord(meta)) {
            clearSuperseded(meta)
            return
        }
        mutable.value = AppDownloadState.Ready(meta.versionName, meta.fileName, actual, meta.mode)
    }

    /** The durable record is still EXACTLY the one this restore started from. */
    private fun isCurrentRecord(meta: DownloadMeta): Boolean =
        DownloadMeta.fromJson(store.pendingDownloadJson) == meta

    /**
     * Drops the in-memory verifying state only when this restore still owns it
     * and no writer has started; a settled record must not leave a spinner or a
     * later Ready/Failed verdict behind.
     */
    private fun clearSuperseded(meta: DownloadMeta) {
        synchronized(writerLock) {
            val current = mutable.value
            if (writer == null && current is AppDownloadState.Verifying &&
                current.versionName == meta.versionName
            ) {
                mutable.value = AppDownloadState.Idle
            }
        }
    }

    private fun publishPaused(owner: Writer) {
        val meta = DownloadMeta.fromJson(store.pendingDownloadJson)
        if (meta == null) {
            publish(owner, AppDownloadState.Idle)
            return
        }
        val part = partFile(meta)
        val bytes = if (part.isFile) part.length() else meta.receivedBytes
        publish(
            owner,
            if (bytes > 0L) {
                AppDownloadState.Paused(meta.versionName, bytes, meta.totalBytes)
            } else {
                AppDownloadState.Idle
            },
        )
    }

    private fun publishPausedNoWriter() {
        val meta = DownloadMeta.fromJson(store.pendingDownloadJson)
        if (meta == null) {
            if (mutable.value is AppDownloadState.InProgress) mutable.value = AppDownloadState.Idle
            return
        }
        val part = partFile(meta)
        val bytes = if (part.isFile) part.length() else meta.receivedBytes
        synchronized(writerLock) {
            if (writer == null) {
                mutable.value = if (bytes > 0L) {
                    AppDownloadState.Paused(meta.versionName, bytes, meta.totalBytes)
                } else {
                    AppDownloadState.Idle
                }
            }
        }
    }

    private fun prepareStaging(meta: DownloadMeta) {
        stagingDir.mkdirs()
        val prefix = tagPrefix(meta)
        stagingDir.listFiles()?.forEach { file ->
            if (!file.name.startsWith(prefix)) file.delete()
        }
    }

    private fun checkDisk(meta: DownloadMeta) {
        val needed = (meta.totalBytes.takeIf { it > 0L } ?: 0L) + UpdateConfig.DISK_HEADROOM_BYTES
        val usable = stagingDir.usableSpace
        if (usable in 1L until needed) {
            throw StageFailure(meta.versionName, DownloadFailure.DISK, resumable = false)
        }
    }

    /**
     * The release's own SHA256SUMS map. It binds the full APK and, when a
     * delta is published, the manifest and patch as well.
     */
    private suspend fun fetchChecksums(owner: Writer, meta: DownloadMeta): Map<String, String> {
        val response = try {
            transport.open(meta.checksumsUrl, null, null)
        } catch (cancellation: CancellationException) {
            throw cancellation
        } catch (failure: Exception) {
            throw StageFailure(meta.versionName, DownloadFailure.NETWORK, resumable = true)
        }
        checkCancelled(owner)
        val text = try {
            response.stream.use { readBounded(it, AndroidReleaseFeed.MAX_CHECKSUMS_BYTES) }
        } catch (cancellation: CancellationException) {
            throw cancellation
        } catch (failure: Exception) {
            throw StageFailure(meta.versionName, DownloadFailure.NETWORK, resumable = true)
        }
        checkCancelled(owner)
        return Sha256Sums.parse(text)
    }

    private fun readBounded(input: InputStream, limit: Long): String {
        val builder = StringBuilder()
        val buffer = ByteArray(8 * 1024)
        var total = 0L
        while (true) {
            val count = input.read(buffer)
            if (count < 0) break
            total += count
            if (total > limit) throw IOException("checksums-oversized")
            builder.append(String(buffer, 0, count, Charsets.UTF_8))
        }
        return builder.toString()
    }

    private fun sha256(file: File): String = sha256(null, file)

    private fun sha256(owner: Writer?, file: File): String {
        val digest = MessageDigest.getInstance("SHA-256")
        file.inputStream().use { input ->
            val buffer = ByteArray(256 * 1024)
            while (true) {
                owner?.let { checkCancelled(it) }
                val count = input.read(buffer)
                if (count < 0) break
                digest.update(buffer, 0, count)
            }
        }
        return digest.digest().joinToString("") { "%02x".format(it) }
    }

    private fun partFile(meta: DownloadMeta): File = File(stagingDir, "${tagPrefix(meta)}.part")

    private fun apkFile(meta: DownloadMeta): File = File(stagingDir, meta.fileName)

    private fun apkFile(fileName: String): File = File(stagingDir, fileName)

    private fun tagPrefix(meta: DownloadMeta): String =
        meta.tag.replace('/', '_').replace('\\', '_').take(80)

    private class StageFailure(
        val versionName: String,
        val kind: DownloadFailure,
        val resumable: Boolean,
    ) : Exception(kind.name)

    private companion object {
        const val PROGRESS_INTERVAL_MS = 200L
    }
}
