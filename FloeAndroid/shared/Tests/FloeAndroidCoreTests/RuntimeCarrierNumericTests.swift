// G02 typed-carrier numeric byte accounting (job-bb6076374ae04500).
//
// The Kotlin consumer (pinned kotlinx-serialization-json 1.9.0) parses the
// ACTUAL Foundation JSON frame and derives `pageBytes`/`valueBytes` from
// `JsonObject.toString()`. kotlinx preserves the numeric LEXEME it parsed;
// therefore the producer must declare the byte count of the token Foundation
// actually emits (e.g. NSNumber(1.0) -> `1`, NSNumber(1e-6) ->
// `9.9999999999999995e-07`), not a Swift `Double.toString` imitation.
//
// The authoritative cross-language proof is the JVM test in the private
// qualification lane, which feeds these exported frames through the REAL
// `RuntimeBootstrapCoordinator.parseEffectPage` decoder. This host test pins
// the producer side and the negative-control regression: before the fix the
// integral-Double case declared one byte more than the wire and the actual
// Kotlin decoder returned ProtocolMismatch.
import XCTest
import Foundation
import FloeCore
@testable import FloeAndroidCore

final class RuntimeCarrierNumericTests: XCTestCase {

    private var fixtureDirectory: String? {
        ProcessInfo.processInfo.environment["FLOE_CARRIER_NUMERIC_FIXTURE_DIR"]
    }

    /// Numeric-only documents: the Foundation wire page and the Kotlin
    /// canonical page are byte-identical (no strings that Foundation escapes
    /// differently), so the independent expectation is the ACTUAL wire page
    /// size, not a second copy of the production formatter.
    private let numericCases: [(name: String, document: DesignJSONValue)] = [
        ("integral-double", .object(["n": .number(1.0)])),
        ("positive-zero", .object(["n": .number(0.0)])),
        ("negative-zero", .object(["n": .number(-0.0)])),
        ("fraction-tenth", .object(["n": .number(0.1)])),
        ("fraction-123.456", .object(["n": .number(123.456)])),
        ("exponent-boundary-1e-3", .object(["n": .number(0.001)])),
        ("exponent-boundary-1e-4", .object(["n": .number(0.0001)])),
        ("exponent-boundary-1e-6", .object(["n": .number(0.000001)])),
        ("exponent-boundary-1e7", .object(["n": .number(10_000_000.0)])),
        ("exponent-boundary-1e8", .object(["n": .number(100_000_000.0)])),
        ("exact-int64-max", .object(["n": .integer(Int64.max)])),
        ("exact-int64-min", .object(["n": .integer(Int64.min)])),
        ("exact-uint64-max", .object(["n": .unsigned(UInt64.max)])),
        ("exact-uint64-2^53+1", .object(["n": .unsigned(9_007_199_254_740_993)])),
        ("decimal-tenth", .object(["n": .decimal(Decimal(string: "0.1")!)])),
        ("decimal-precision", .object(["n": .decimal(
            Decimal(string: "123.4567890123456789")!)])),
        ("decimal-small", .object(["n": .decimal(Decimal(string: "0.0000001")!)])),
        ("bool-mixed-numeric", .object([
            "ok": .bool(true), "no": .bool(false), "n": .number(1.0),
        ])),
        ("nested-numeric-array", .object([
            "values": .array([.number(1.0), .number(-0.0), .integer(2),
                              .unsigned(UInt64.max), .decimal(Decimal(string: "0.10")!)]),
        ])),
        ("null-mixed", .object(["none": .null, "n": .number(2.0)])),
    ]

    /// Mixed numeric + string documents pin the Kotlin string lexemes too.
    /// These literals are explicit expected encodings (not generated by the
    /// production formatter) and run only on Darwin where the Foundation
    /// numeric tokens are the ones pinned below.
    private let mixedCases: [(name: String, document: DesignJSONValue, canonical: String)] = [
        ("mixed-escapes-cjk-emoji", .object([
            "ok": .bool(true),
            "no": .bool(false),
            "url": .string("https://example.com/a/b?x=1&y=2"),
            "ctrl": .string("a\u{0001}b"),
            "cjk": .string("中文"),
            "emoji": .string("😀"),
            "n": .number(1.0),
        ]), "{\"cjk\":\"中文\",\"ctrl\":\"a\\u0001b\",\"emoji\":\"😀\",\"n\":1,"
            + "\"no\":false,\"ok\":true,\"url\":\"https://example.com/a/b?x=1&y=2\"}"),
        ("mixed-quote-backslash", .object([
            "s": .string("a\"b\\c"),
            "n": .number(-0.0),
            "d": .decimal(Decimal(string: "0.1")!),
        ]), "{\"d\":0.1,\"n\":-0,\"s\":\"a\\\"b\\\\c\"}"),
    ]

    func testTypedCarrierNumericCorpusDeclaresKotlinEquivalentBytes() throws {
        var cases: [[String: Any]] = []
        var failures: [String] = []

        func record(name: String, document: DesignJSONValue,
                    documentKey: String, expected: Int?) {
            let item = RuntimeEffectItem(
                sequence: 1, kind: .accepted, code: nil, detail: nil,
                page: documentKey == "page" ? document : nil,
                value: documentKey == "value" ? document : nil)
            let declared = documentKey == "page" ? item.pageBytes : item.valueBytes
            if let expected, declared != expected {
                failures.append("\(name): declared=\(declared.map(String.init) ?? "nil") "
                    + "expected=\(expected)")
            }
            guard let frame = Self.frame(correlation: "numeric-\(name)",
                                         receipt: Self.receipt,
                                         item: item) else {
                failures.append("\(name): frame failed to encode")
                return
            }
            cases.append([
                "name": name,
                "documentKey": documentKey,
                "correlation": "numeric-\(name)",
                "receipt": Self.receipt,
                "wire": frame,
                "document": RuntimeEffectDocumentProjection.foundationObject(document),
            ])
        }

        for (index, entry) in numericCases.enumerated() {
            let key = index.isMultiple(of: 2) ? "page" : "value"
            // Independent expectation: the actual Foundation page wire bytes.
            // Numeric-only documents have no Foundation/Kotlin string escape
            // divergence, so this is exactly the Kotlin canonical page size.
            let pageObject = ["v": RuntimeEffectDocumentProjection.foundationObject(entry.document)]
            let wirePage = try JSONSerialization.data(withJSONObject: pageObject,
                                                      options: [.sortedKeys])
            // `{"v":<document>}` has 6 fixed bytes of wrapper.
            let expected = wirePage.count - 6
            record(name: entry.name, document: entry.document,
                   documentKey: key, expected: expected)
        }

        for entry in mixedCases {
            let expected = entry.canonical.utf8.count
            record(name: entry.name, document: entry.document,
                   documentKey: "value", expected: expected)
        }

        if let directory = fixtureDirectory {
            try FileManager.default.createDirectory(
                atPath: directory, withIntermediateDirectories: true)
            let payload: [String: Any] = [
                "schema": "floe.g02.carrier-numeric-fixtures/1",
                "job": "job-bb6076374ae04500",
                "cases": cases,
            ]
            let data = try JSONSerialization.data(withJSONObject: payload,
                                                  options: [.sortedKeys])
            try data.write(to: URL(fileURLWithPath: directory)
                .appendingPathComponent("carrier-numeric-wire.json"))
        }

        XCTAssertTrue(failures.isEmpty,
                      "numeric byte declarations diverge from the emitted wire:\n"
                        + failures.joined(separator: "\n"))
    }

    func testNonfiniteCarrierValuesRefuseHonestly() throws {
        let pump = FacadeEffectPump(generation: 1)
        let receipt = try XCTUnwrap(pump.register(correlationID: "numeric-nonfinite"))
        let nonfinite: [(String, DesignJSONValue)] = [
            ("infinity", .object(["n": .number(.infinity)])),
            ("negative-infinity", .object(["n": .number(-.infinity)])),
            ("nan", .object(["n": .number(.nan)])),
            ("decimal-nan", .object(["n": .decimal(Decimal.nan)])),
        ]
        for (name, document) in nonfinite {
            let item = RuntimeEffectItem(sequence: 1, kind: .accepted, code: nil,
                                         detail: nil, page: document, value: nil)
            XCTAssertEqual(item.encodedBytes, Int.max, "\(name): must be unencodable")
            let outcome = pump.append(receipt: receipt, kind: .accepted, code: nil,
                                      detail: nil, page: document, value: nil)
            guard case .refused(.payloadTooLarge) = outcome else {
                return XCTFail("\(name): nonfinite carrier must be refused typed, got \(outcome)")
            }
            XCTAssertFalse(pump.isTerminal(receipt: receipt))
        }
    }

    func testDirectNSNumberSupplementalTokensFollowTheWireEncoder() throws {
        // Supplemental (NOT a DesignJSONValue carrier): the counting helper
        // must follow Foundation's actual token for every NSNumber flavor,
        // never `objCType` guesses (Int8(1) is numeric `1`, not `true`).
        let numbers: [(String, NSNumber)] = [
            ("double-1.0", NSNumber(value: 1.0)),
            ("double-1e-6", NSNumber(value: 0.000001)),
            ("decimal-0.1", NSDecimalNumber(string: "0.1")),
            ("uint64-max", NSNumber(value: UInt64.max)),
            ("bool-true", NSNumber(value: true)),
            ("int8-1", NSNumber(value: Int8(1))),
            ("float-0.5", NSNumber(value: Float(0.5))),
        ]
        for (name, number) in numbers {
            let wire = try JSONSerialization.data(withJSONObject: [number])
            let token = wire.dropFirst().dropLast()
            let canonical = try XCTUnwrap(
                FacadeFrameBudget.canonicalSerializedBytes(["v": number]), name)
            // `{"v":` + token + `}` = 6 fixed bytes.
            XCTAssertEqual(canonical, token.count + 6, name)
        }
    }

    // MARK: - Helpers

    private static let receipt = "op:v1:" + String(repeating: "ab", count: 16)

    private static func frame(correlation: String, receipt: String,
                              item: RuntimeEffectItem) -> String? {
        let object: [String: Any] = [
            "ok": true,
            "schema": BridgeV3.effectSchema,
            "correlationID": correlation,
            "cursor": ["operationReceiptID": receipt, "sequence": item.sequence],
            "effects": [item.jsonObject],
            "hasMore": false,
            "resyncRequired": false,
        ]
        guard RuntimeFacadeBridge.finalizeWithin(
            object,
            pageBudgetBytes: FacadeFrameBudget.pageBudgetBytes,
            outerMarginBytes: correlation.utf8.count + 64) != nil else {
            return nil
        }
        // AndroidBridge.exchange stamps the outer v3 wrapper on the SAME
        // object the handler returned and encodes once. Never re-parse the
        // handler bytes here: a JSON round-trip would turn NSDecimalNumber
        // into Double and normalize -0, which is not what the real bridge
        // does (and would corrupt the very lexemes under test).
        var full = object
        full["version"] = BridgeV3.version
        full["requestID"] = correlation
        guard let fullData = try? JSONSerialization.data(withJSONObject: full,
                                                         options: [.sortedKeys]) else {
            return nil
        }
        return String(decoding: fullData, as: UTF8.self)
    }
}
