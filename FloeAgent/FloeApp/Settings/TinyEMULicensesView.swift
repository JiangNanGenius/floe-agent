/// One license or notice document copied into the app bundle.
struct BundledLicenseDocument: Identifiable, Hashable {
    /// Bundle-relative path; also the stable identity of the document.
    let relativePath: String
    let title: String
    let detail: String
    /// Required documents stay listed even when a build omitted the file, so
    /// the absence is visible instead of silently reducing the notices.
    let isRequired: Bool
    /// Optional grouping label for the list section.
    let section: String

    var id: String { relativePath }
}

