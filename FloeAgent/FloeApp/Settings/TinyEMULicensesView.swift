/// One runtime component whose versions and license identifiers are recorded
/// in the generated repository inventory. The bundled notice text (when one
/// ships) is the operative declaration; this row is the index entry.
struct LicenseComponent: Identifiable, Hashable {
    let name: String
    let version: String
    let license: String
    let source: String

    var id: String { "\(name)@\(version)" }

    init(_ name: String, _ version: String, _ license: String, _ source: String) {
        self.name = name
        self.version = version
        self.license = license
        self.source = source
    }
}

