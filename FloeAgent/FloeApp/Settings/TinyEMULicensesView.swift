// Settings exposes exactly one legal entry (Diagnostics & About → Legal →
// Third-Party Licenses). This file is that entry: it keeps the complete
// TinyEMU/slirp notices and every other bundled dependency notice readable and
// copyable in place, and lists the components whose license text ships
// separately in the repository inventory.
//
// Nothing is summarised away. The full notices come from the files copied into
// the app bundle at build time; a notice that is missing from a build is
// reported as unavailable instead of being hidden. The component summary
// mirrors `FloeAgent/LICENSES-THIRD-PARTY.md` (generated by
// `scripts/license_inventory.sh`) for versions and sources, while the bundled
// texts remain the operative declarations.
//
// The file name is retained from the previous TinyEMU-only view: it is now the
// single unified license screen, so `DiagnosticsAboutView` has one entry.

