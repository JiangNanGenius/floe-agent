    static func documents(in resourceRoot: URL?, fileManager: FileManager = .default) -> [BundledLicenseDocument] {
        guard let root = resourceRoot else { return [tinyEMU] }
        var documents = [tinyEMU]
        documents += known.filter { fileManager.fileExists(atPath: root.appendingPathComponent($0.relativePath).path) }
        documents += fontDocuments(in: root, fileManager: fileManager)
        return documents
    }

    /// One entry per bundled font family that carries its own LICENSE.txt.
    private static func fontDocuments(in root: URL, fileManager: FileManager) -> [BundledLicenseDocument] {
        let fontsRoot = root.appendingPathComponent("Fonts/Bundled", isDirectory: true)
        guard let families = try? fileManager.contentsOfDirectory(
            at: fontsRoot,
            includingPropertiesForKeys: [.isDirectoryKey],
            options: [.skipsHiddenFiles]
        ) else { return [] }
        return families
            .sorted { $0.lastPathComponent < $1.lastPathComponent }
            .compactMap { family in
                let license = family.appendingPathComponent("LICENSE.txt")
                guard fileManager.fileExists(atPath: license.path) else { return nil }
                let name = family.lastPathComponent
                return BundledLicenseDocument(
                    relativePath: "Fonts/Bundled/\(name)/LICENSE.txt",
                    title: "字体 / Font: \(name)",
                    detail: "OFL-1.1 或厂商授权 / OFL-1.1 or vendor grant",
                    isRequired: false,
                    section: "字体 / Fonts"
                )
            }
    }
}

