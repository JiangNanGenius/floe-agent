// Settings exposes exactly one legal entry (Diagnostics & About → Legal →
// Third-Party Licenses). This file is that entry. It reads the packaged
// inventory that `scripts/license_inventory.sh` generates from the real
// dependency pins and upstream license files, and it reads every notice text
// from the file copied into this build:
//
//   Licenses/third-party-inventory.json   generated component + notice index
//   <bundlePath>                          complete notice text, verbatim
//
// There is deliberately no Swift-side copy of the dependency table: a version
// or license that is not in the generated manifest cannot appear on screen, and
// a notice missing from the build is shown as unavailable instead of hidden.
// The file name is retained from the previous TinyEMU-only view.

#if canImport(SwiftUI) && canImport(UIKit)
import SwiftUI
