/// Explicit commands at the model boundary; never expose EDAEdit's synthesized
/// enum payload as an undocumented input format.
nonisolated enum StudioElectronicsContract {
    enum Action: Sendable { case edits([EDAEdit]), undo, redo }
    struct Capabilities: Encodable, Sendable {
        let revision: String
        let editCommands: [String]
        let nativePutKinds: [String]
        let runActions: [String]
        let exportFormats: [String]
        let assemblyVariants: [String]
        let commandFormats: [String: String]
        let examplesJSON: String
        let limitations: [String]
    }
    static let commands = ["rename", "sheet.create", "component.place", "component.set", "component.remove",
        "symbol.move", "wire.put", "label.put", "junction.put", "noConnect.put", "schematic.remove", "board.remove", "native.put", "undo", "redo"]
    static let nativeKinds = ["symbolDefinition", "footprintDefinition", "component", "sheet", "symbolPlacement",
        "wire", "junction", "noConnect", "label", "bus", "sheetLink", "board", "footprint", "track", "via", "zone", "keepout", "hole", "simulation"]
    static let runActions = ["eda.erc", "eda.drc", "eda.netlist", "eda.forwardAnnotation", "eda.export"]
    static let commandFormats: [String: String] = [
        "rename": "{op:rename,title:string}",
        "sheet.create": "{op:sheet.create,name:string,id?:new UUID}",
        "component.place": "{op:component.place,sheetID:UUID,symbolID:UUID,x:number,y:number,id?:new component UUID,placementID?:new placement UUID,footprintID?:UUID,reference?:string,value?:string,angle?:degrees,mirrored?:boolean}. Omitted IDs are generated by the host; existing components use component.set.",
        "component.set": "{op:component.set,componentID:UUID,reference?:string,value?:string,footprintID?:UUID or null to clear,fields?:string dictionary,excludedVariants?:string array}. Only provided fields change.",
        "component.remove": "{op:component.remove,componentID:UUID}. Removes logical placements; the physical board is retained for explicit synchronization.",
        "symbol.move": "{op:symbol.move,sheetID:UUID,objectID:placement UUID,x:number,y:number,angle?:degrees,mirrored?:boolean}",
        "wire.put": "{op:wire.put,sheetID:UUID,id?:wire UUID,points:[{x:number,y:number},...]}. At least two points; an existing ID replaces that wire.",
        "label.put": "{op:label.put,sheetID:UUID,id?:label UUID,name:string,x:number,y:number,scope?:local|global|hierarchical}",
        "junction.put": "{op:junction.put,sheetID:UUID,id?:marker UUID,x:number,y:number}",
        "noConnect.put": "{op:noConnect.put,sheetID:UUID,id?:marker UUID,x:number,y:number}",
        "schematic.remove": "{op:schematic.remove,sheetID:UUID,objectID:UUID}. Removing the last symbol unit also removes that logical component.",
        "board.remove": "{op:board.remove,boardID:UUID,objectID:UUID}. Removes one unlocked physical object, not the board.",
        "native.put": "{op:native.put,kind:nativePutKinds entry,value:complete native record,sheetID?:UUID,boardID?:UUID}. sheetID is required only for symbolPlacement/wire/junction/noConnect/label/bus/sheetLink; boardID only for footprint/track/via/zone/keepout/hole. Other parent fields are rejected. Preserve all fields of an existing record; omit nil optionals. Locked footprints/tracks cannot change.",
        "undo": "[{op:undo}]. One command only, with the exact outer expectedRevision.",
        "redo": "[{op:redo}]. One command only, with the exact outer expectedRevision."
    ]
    static let guide = "Use a plain JSON array of explicit commands listed in electronicsCapabilities. Each command has op and documented flat fields; copy its complete examples with actual sheet/symbol/board IDs from this original. Coordinates and widths are millimetres, angles degrees. native.put accepts one complete record as value, not EDAEdit's synthesized enum payload; missing/unknown fields return a path. An entire batch validates before one revision/CAS save. undo/redo must be a single command. Read the actual saved state after editing. studio.run supports eda.erc, eda.drc, eda.netlist, eda.forwardAnnotation, eda.export with inputJSON.expectedRevision; drc/forwardAnnotation optionally take boardID, export additionally takes format and optional variant/boardID. inspectFrame accepts expectedRevision plus optional sheetID or boardID and maximumPixelSize."
    static func capabilities(_ project: EDAProject) throws -> Capabilities {
        var examples: [[String: Any]] = [["op": "rename", "title": project.title]]
        if let sheet = project.sheets.first, let symbol = project.symbols.first {
            var placement: [String: Any] = ["op": "component.place", "sheetID": sheet.id.uuidString,
                "symbolID": symbol.id.uuidString, "reference": nextReference(symbol.referencePrefix, project: project),
                "value": symbol.name, "x": 25.4, "y": 25.4, "angle": 0, "mirrored": false]
            if let footprint = project.footprints.first { placement["footprintID"] = footprint.id.uuidString }
            examples.append(placement)
            examples.append(["op": "wire.put", "sheetID": sheet.id.uuidString,
                "points": [["x": 10.0, "y": 10.0], ["x": 20.0, "y": 10.0]]])
            let encoded = try JSONEncoder().encode(symbol)
            if encoded.count <= 12_000 {
                examples.append(["op": "native.put", "kind": "symbolDefinition", "value": try JSONSerialization.jsonObject(with: encoded)])
            }
        }
        let bytes = try JSONSerialization.data(withJSONObject: examples, options: [.sortedKeys])
        return .init(revision: String(project.revision), editCommands: commands, nativePutKinds: nativeKinds,
            runActions: runActions, exportFormats: EDAExportFormat.allCases.map(\.rawValue),
            assemblyVariants: project.variants,
            commandFormats: commandFormats,
            examplesJSON: String(decoding: bytes, as: UTF8.self), limitations: [
                "Examples are alternatives, not a request to insert test components. Use actual IDs from this original.",
                "native.put replaces one complete native record. Copy all encoded fields, omit nil optional fields, and preserve unknown source content. Extra keys are rejected with a field path.",
                "Manual 45-degree routing and supported DRC are available; shove routing, differential tuning, zone refill, Gerber/Excellon and external EDA import are not implemented yet.",
                "3D currently extrudes the measured board, cutouts and holes; component model loading and SPICE simulation are not implemented."
            ])
    }
    static func nextReference(_ prefix: String, project: EDAProject) -> String {
        let used = Set(project.components.map(\.reference))
        var i = 1; while used.contains(prefix + String(i)) { i += 1 }
        return prefix + String(i)
    }
    static func decode(_ text: String, project: EDAProject, cancelled: @Sendable () -> Bool = { false }) throws -> Action {
        guard text.utf8.count <= 2 * 1_024 * 1_024 else { throw failure("$", "input exceeds 2 MiB") }
        let raw: Any
        do { raw = try JSONSerialization.jsonObject(with: Data(text.utf8)) }
        catch { throw failure("$", "expected a JSON array of plain commands") }
        guard let values = raw as? [[String: Any]], (1...100).contains(values.count) else { throw failure("$", "use 1...100 command objects") }
        if values.count == 1, let op = values[0]["op"] as? String, ["undo", "redo"].contains(op) {
            try keys(values[0], ["op"], "$[0]")
            return op == "undo" ? .undo : .redo
        }
        var edits: [EDAEdit] = [], candidate = project
        for (i, value) in values.enumerated() {
            if cancelled() { throw EDAError.cancelled }
            edits += try command(value, project: candidate, path: "$[\(i)]")
            var preview = try EDAEditingSession(project: project)
            do { try preview.apply(edits, expectedRevision: project.revision, cancelled: cancelled) }
            catch { throw failure("$[\(i)]", String(describing: error)) }
            candidate = preview.project
        }
        return .edits(edits)
    }
    private static func command(_ v: [String: Any], project p: EDAProject, path: String) throws -> [EDAEdit] {
        let op = try string(v, "op", path)
        func uuid(_ key: String) throws -> UUID { try id(v, key, path) }
        func point() throws -> EDAPoint { .init(try number(v, "x", path), try number(v, "y", path)) }
        func sheet() throws -> UUID {
            let id = try uuid("sheetID")
            guard p.sheets.contains(where: { $0.id == id }) else { throw failure(path + ".sheetID", "sheet is absent from this original") }
            return id
        }
        switch op {
        case "rename": try keys(v, ["op", "title"], path); return [.rename(try string(v, "title", path))]
        case "sheet.create":
            try keys(v, ["op", "id", "name"], path)
            let newID = try optionalID(v, "id", path) ?? UUID()
            guard !p.sheets.contains(where: { $0.id == newID }) else { throw failure(path + ".id", "sheet already exists") }
            return [.putSheet(.init(id: newID, name: try string(v, "name", path)))]
        case "component.place":
            try keys(v, ["op", "id", "placementID", "sheetID", "symbolID", "footprintID", "reference", "value", "x", "y", "angle", "mirrored"], path)
            let sheetID = try sheet(), symbolID = try uuid("symbolID")
            guard let symbol = p.symbols.first(where: { $0.id == symbolID }) else { throw failure(path + ".symbolID", "symbol is absent from this library") }
            let componentID = try optionalID(v, "id", path) ?? UUID()
            guard !p.components.contains(where: { $0.id == componentID }) else { throw failure(path + ".id", "component already exists; use component.set") }
            let component = EDAComponent(id: componentID, symbolID: symbolID, footprintID: try optionalID(v, "footprintID", path),
                reference: try optionalString(v, "reference", path) ?? nextReference(symbol.referencePrefix, project: p),
                value: try optionalString(v, "value", path) ?? symbol.name)
            let placement = EDASymbolPlacement(id: try optionalID(v, "placementID", path) ?? UUID(), componentID: component.id,
                position: try point(), angle: try optionalNumber(v, "angle", path) ?? 0, mirrored: try optionalBool(v, "mirrored", path) ?? false)
            return [.putComponent(component), .placeSymbol(sheet: sheetID, placement)]
        case "component.set":
            try keys(v, ["op", "componentID", "reference", "value", "footprintID", "fields", "excludedVariants"], path)
            let componentID = try uuid("componentID")
            guard var component = p.components.first(where: { $0.id == componentID }) else { throw failure(path + ".componentID", "component is absent") }
            if let reference = try optionalString(v, "reference", path) { component.reference = reference }
            if let value = try optionalString(v, "value", path) { component.value = value }
            if v.keys.contains("footprintID") {
                component.footprintID = v["footprintID"] is NSNull ? nil : try optionalID(v, "footprintID", path)
            }
            if let raw = v["fields"] {
                guard let fields = raw as? [String: String] else { throw failure(path + ".fields", "expected string values") }
                component.fields = fields
            }
            if let raw = v["excludedVariants"] {
                guard let variants = raw as? [String] else { throw failure(path + ".excludedVariants", "expected string array") }
                component.excludedVariants = Set(variants)
            }
            return [.putComponent(component)]
        case "component.remove": try keys(v, ["op", "componentID"], path); return [.removeComponent(try uuid("componentID"))]
        case "symbol.move":
            try keys(v, ["op", "sheetID", "objectID", "x", "y", "angle", "mirrored"], path)
            let sheetID = try sheet(), objectID = try uuid("objectID")
            guard var value = p.sheets.first(where: { $0.id == sheetID })?.symbols.first(where: { $0.id == objectID }) else { throw failure(path + ".objectID", "symbol placement is absent") }
            value.position = try point()
            if let angle = try optionalNumber(v, "angle", path) { value.angle = angle }
            if let mirror = try optionalBool(v, "mirrored", path) { value.mirrored = mirror }
            return [.placeSymbol(sheet: sheetID, value)]
        case "wire.put":
            try keys(v, ["op", "sheetID", "id", "points"], path)
            guard let values = v["points"] as? [[String: Any]], (2...10_000).contains(values.count) else { throw failure(path + ".points", "use 2...10000 {x,y} points") }
            let points = try values.enumerated().map { index, value -> EDAPoint in
                let at = path + ".points[\(index)]"; try keys(value, ["x", "y"], at)
                return .init(try number(value, "x", at), try number(value, "y", at))
            }
            return [.putWire(sheet: try sheet(), .init(id: try optionalID(v, "id", path) ?? UUID(), points: points))]
        case "label.put":
            try keys(v, ["op", "sheetID", "id", "name", "x", "y", "scope"], path)
            let name = try optionalString(v, "scope", path) ?? "local"
            guard let scope = EDALabelScope(rawValue: name) else { throw failure(path + ".scope", "use local, global or hierarchical") }
            return [.putLabel(sheet: try sheet(), .init(id: try optionalID(v, "id", path) ?? UUID(), name: try string(v, "name", path), position: try point(), scope: scope))]
        case "junction.put", "noConnect.put":
            try keys(v, ["op", "sheetID", "id", "x", "y"], path)
            let marker = EDAJunction(id: try optionalID(v, "id", path) ?? UUID(), position: try point()), sheetID = try sheet()
            return op == "junction.put" ? [.putJunction(sheet: sheetID, marker)] : [.putNoConnect(sheet: sheetID, marker)]
        case "schematic.remove":
            try keys(v, ["op", "sheetID", "objectID"], path)
            let sheetID = try sheet(), objectID = try uuid("objectID")
            if let instance = p.sheets.first(where: { $0.id == sheetID })?.symbols.first(where: { $0.id == objectID }),
               p.sheets.flatMap(\.symbols).filter({ $0.componentID == instance.componentID }).count == 1 {
                return [.removeComponent(instance.componentID)]
            }
            return [.removeSchematicObject(sheet: sheetID, object: objectID)]
        case "board.remove":
            try keys(v, ["op", "boardID", "objectID"], path)
            return [.removeBoardObject(board: try uuid("boardID"), object: try uuid("objectID"))]
        case "native.put":
            try keys(v, ["op", "kind", "sheetID", "boardID", "value"], path)
            return [try native(v, project: p, path: path)]
        default: throw failure(path + ".op", "unsupported command; inspect electronicsCapabilities")
        }
    }
    private static func native(_ v: [String: Any], project: EDAProject, path: String) throws -> EDAEdit {
        let kind = try string(v, "kind", path)
        let sheetKinds: Set<String> = ["symbolPlacement", "wire", "junction", "noConnect", "label", "bus", "sheetLink"]
        let boardKinds: Set<String> = ["footprint", "track", "via", "zone", "keepout", "hole"]
        var allowed: Set<String> = ["op", "kind", "value"]
        if sheetKinds.contains(kind) { allowed.insert("sheetID") }
        if boardKinds.contains(kind) { allowed.insert("boardID") }
        try keys(v, allowed, path)
        guard let object = v["value"] as? [String: Any] else { throw failure(path + ".value", "expected the complete native record") }
        func decode<T: Codable>(_ type: T.Type) throws -> T {
            do {
                let value = try JSONDecoder().decode(type, from: JSONSerialization.data(withJSONObject: object))
                let canonical = try JSONSerialization.jsonObject(with: JSONEncoder().encode(value))
                try rejectUnknown(object, canonical: canonical, path: path + ".value")
                return value
            } catch let error as DecodingError {
                let location: [CodingKey]
                switch error { case .keyNotFound(let key, let context): location = context.codingPath + [key]
                case .typeMismatch(_, let context), .valueNotFound(_, let context), .dataCorrupted(let context): location = context.codingPath
                @unknown default: location = [] }
                throw failure(path + ".value" + location.map { "." + $0.stringValue }.joined(), "missing or invalid native field; copy the complete record from studio.read")
            }
        }
        func sheet() throws -> UUID { try id(v, "sheetID", path) }
        func board() throws -> UUID { try id(v, "boardID", path) }
        switch kind {
        case "symbolDefinition": return .putSymbol(try decode(EDASymbolDefinition.self))
        case "footprintDefinition": return .putFootprintDefinition(try decode(EDAFootprintDefinition.self))
        case "component": return .putComponent(try decode(EDAComponent.self))
        case "sheet": return .putSheet(try decode(EDASheet.self))
        case "symbolPlacement": return .placeSymbol(sheet: try sheet(), try decode(EDASymbolPlacement.self))
        case "wire": return .putWire(sheet: try sheet(), try decode(EDAWire.self))
        case "junction": return .putJunction(sheet: try sheet(), try decode(EDAJunction.self))
        case "noConnect": return .putNoConnect(sheet: try sheet(), try decode(EDAJunction.self))
        case "label": return .putLabel(sheet: try sheet(), try decode(EDANetLabel.self))
        case "bus": return .putBus(sheet: try sheet(), try decode(EDABus.self))
        case "sheetLink": return .putSheetLink(sheet: try sheet(), try decode(EDASheetLink.self))
        case "board":
            let value = try decode(EDABoard.self)
            if let old = project.boards.first(where: { $0.id == value.id }) {
                for locked in old.footprints where locked.locked { guard value.footprints.contains(locked) else { throw failure(path + ".value.footprints", "locked footprint must be preserved") } }
                for locked in old.tracks where locked.locked { guard value.tracks.contains(locked) else { throw failure(path + ".value.tracks", "locked track must be preserved") } }
            }
            return .putBoard(value)
        case "footprint":
            let boardID = try board(), value = try decode(EDAFootprint.self)
            if let old = project.boards.first(where: { $0.id == boardID })?.footprints.first(where: { $0.id == value.id }), old.locked, old != value { throw failure(path + ".value", "locked footprint must be preserved") }
            return .putFootprint(board: boardID, value)
        case "track":
            let boardID = try board(), value = try decode(EDATrack.self)
            if let old = project.boards.first(where: { $0.id == boardID })?.tracks.first(where: { $0.id == value.id }), old.locked, old != value { throw failure(path + ".value", "locked track must be preserved") }
            return .putTrack(board: boardID, value)
        case "via": return .putVia(board: try board(), try decode(EDAVia.self))
        case "zone": return .putZone(board: try board(), try decode(EDAZone.self))
        case "keepout": return .putKeepout(board: try board(), try decode(EDAKeepout.self))
        case "hole": return .putHole(board: try board(), try decode(EDAHole.self))
        case "simulation": return .putSimulation(try decode(EDASimulationSetup.self))
        default: throw failure(path + ".kind", "unsupported native record type")
        }
    }
    private static func rejectUnknown(_ input: Any, canonical: Any, path: String) throws {
        if let input = input as? [String: Any], let encoded = canonical as? [String: Any] {
            for key in input.keys.sorted() {
                guard let value = encoded[key] else { throw failure(path + "." + key, "unknown field, or omit this nil optional field") }
                try rejectUnknown(input[key]!, canonical: value, path: path + "." + key)
            }
        } else if let input = input as? [Any], let encoded = canonical as? [Any] {
            guard input.count == encoded.count else { throw failure(path, "native array changed during decoding") }
            for index in input.indices { try rejectUnknown(input[index], canonical: encoded[index], path: path + "[\(index)]") }
        }
    }
    private static func keys(_ value: [String: Any], _ allowed: Set<String>, _ path: String) throws {
        if let key = Set(value.keys).subtracting(allowed).sorted().first { throw failure(path + "." + key, "unknown field") }
    }
    private static func string(_ value: [String: Any], _ key: String, _ path: String) throws -> String {
        guard let text = value[key] as? String, text.utf8.count <= 128_000 else { throw failure(path + "." + key, "expected a bounded string") }
        return text
    }
    private static func optionalString(_ value: [String: Any], _ key: String, _ path: String) throws -> String? { value[key] == nil ? nil : try string(value, key, path) }
    private static func id(_ value: [String: Any], _ key: String, _ path: String) throws -> UUID {
        guard let id = UUID(uuidString: try string(value, key, path)) else { throw failure(path + "." + key, "expected a UUID from this original") }; return id
    }
    private static func optionalID(_ value: [String: Any], _ key: String, _ path: String) throws -> UUID? { value[key] == nil ? nil : try id(value, key, path) }
    private static func number(_ value: [String: Any], _ key: String, _ path: String) throws -> Double {
        guard let n = value[key] as? NSNumber, CFGetTypeID(n) != CFBooleanGetTypeID(), n.doubleValue.isFinite else { throw failure(path + "." + key, "expected a finite number") }; return n.doubleValue
    }
    private static func optionalNumber(_ value: [String: Any], _ key: String, _ path: String) throws -> Double? { value[key] == nil ? nil : try number(value, key, path) }
    private static func optionalBool(_ value: [String: Any], _ key: String, _ path: String) throws -> Bool? {
        guard let raw = value[key] else { return nil }
        guard let n = raw as? NSNumber, CFGetTypeID(n) == CFBooleanGetTypeID() else { throw failure(path + "." + key, "expected a boolean") }; return n.boolValue
    }
    private static func failure(_ path: String, _ message: String) -> FloeError { .validationFailed("Electronics edit \(path): \(message)") }
}
