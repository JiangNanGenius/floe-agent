private nonisolated struct MusicImportDirectory: Sendable {
    let url: URL
    let device: UInt64
    let inode: UInt64
    init(_ url: URL) throws {
        guard url.standardizedFileURL == url.standardizedFileURL.resolvingSymlinksInPath() else { throw PersonalContentError.changedDocument }
        var value = stat()
        guard lstat(url.path, &value) == 0, (value.st_mode & S_IFMT) == S_IFDIR else { throw PersonalContentError.changedDocument }
        self.url = url; device = UInt64(UInt32(bitPattern: value.st_dev)); inode = UInt64(value.st_ino)
    }
    func validate() throws {
        let current = try Self(url)
        guard current.device == device, current.inode == inode else { throw PersonalContentError.changedDocument }
    }
}

/// Each personal Music project has one durable store and one service-owned
/// transport. Editor windows do not own renders or recorded original files.
@MainActor @Observable final class MusicProjectSession {
    private static var sessions: [UUID: MusicProjectSession] = [:]
    static func requireIdleForDeletion(id: UUID) throws {
        guard let value = sessions[id] else { return }
        guard value.notation?.isBusy != true, !value.notationImporting, !value.notationRestoring, !value.saving, !value.isRendering, !value.isLive, value.previewPresetIndex == nil, value.player?.isPlaying != true, !value.isRecording, !value.isMIDIRecording else { throw PersonalFileActionError.busy }
    }

    /// Read-only lookup; observing audio must not construct an editor, prefetch
    /// waveforms, open a transport session, or create repository directories.
    static func existingForAudioObservation(id: UUID, directory: URL) throws -> MusicProjectSession? {
        guard let value = sessions[id] else { return nil }
        guard value.root.standardizedFileURL.resolvingSymlinksInPath() == directory.standardizedFileURL.resolvingSymlinksInPath() else {
            throw PersonalContentError.changedDocument
        }
        return value
    }

