    static func open(id: UUID, directory: URL, environment: AppEnvironment) async throws -> MusicProjectSession {
        if let value = sessions[id] { return value }
        try MusicNotationPackage.recoverPending(root: directory, parentID: id)
        let repository = try NativeMusicRepository(root: directory)
        let store = try await MusicProjectStore.open(projectID: .init(rawValue: id.uuidString.lowercased()), repository: repository)
        let document = try await store.currentSnapshot()
        let handle = await store.beginSession(ownerToken: "music-editor-" + UUID().uuidString)
        let value = MusicProjectSession(id: id, root: directory, repository: repository, store: store,
            document: document, handle: handle, environment: environment)
        sessions[id] = value
        value.loadWaveforms()
        return value
    }
    /// Host-only restoration fence. Closing the old store session invalidates
    /// pending commit fences before either original directory can be exchanged.
    func beginNotationRestore(expected: MusicNotationSnapshot) async throws -> MusicNotationRestoreAuthority {
        guard expected.parentID == id, expected.musicRevision == document.revision,
              !saving, !notationRestoring, !isRendering, !isRecording, !isMIDIRecording,
              notation?.isBusy != true else { throw PersonalContentError.changedDocument }
        try MusicNotationPackage.requireUnchanged(expected, root: root)
        let ticket = MusicNotationRestoreAuthority(identity: UUID(), ownerToken: handle.ownerToken, oldStore: store, oldDocument: document)
        saving = true; notationRestoring = true; notationRestoreIdentity = ticket.identity
        stopLive(); stopPlayback(); cancelRender(); notation?.invalidateForRestore()
        do { try await store.close(handle) }
        catch { saving = false; notationRestoring = false; notationRestoreIdentity = nil; throw error }
        return ticket
    }
    /// Reopen through the same repository/store authority after atomic exchange
    /// or rollback. A prior restore's late callback cannot adopt this session.
    func finishNotationRestore(_ ticket: MusicNotationRestoreAuthority, store next: MusicProjectStore) async throws {
        guard notationRestoring, notationRestoreIdentity == ticket.identity else { throw PersonalContentError.changedDocument }
        try await store.close(handle)
        let restored = try await next.currentSnapshot()
        guard restored.id == document.id else { throw PersonalContentError.changedDocument }
        let nextHandle = await next.beginSession(ownerToken: ticket.ownerToken)
        guard notationRestoring, notationRestoreIdentity == ticket.identity else { try? await next.close(nextHandle); throw PersonalContentError.changedDocument }
        for task in waveformTasks.values { task.cancel() }
        waveformTasks.removeAll(); waveforms.removeAll(); waveformErrors.removeAll()
        exportedFile = nil; exportedFiles = []
        store = next; document = restored; handle = nextHandle
        if let bytes = try? Data(contentsOf: root.appendingPathComponent("dj-session.json")) {
            dj = try JSONDecoder().decode(MusicDJSession.self, from: bytes)
        } else { dj = nil }
        reconcileSelection()
    }
    func completeNotationRestore(_ ticket: MusicNotationRestoreAuthority) {
        guard notationRestoring, notationRestoreIdentity == ticket.identity else { return }
        saving = false; notationRestoring = false; notationRestoreIdentity = nil
        notation?.invalidateForRestore(); loadWaveforms()
        Task { await publishSavedChange(previousRevision: ticket.oldDocument.revision) }
    }
    func registerNotationExport(_ url: URL) {
        exportedFile = url
        if !exportedFiles.contains(url) { exportedFiles.append(url) }
    }

    func apply(_ operations: [MusicEditOp], expectedRevision: Int64? = nil) async throws {
        guard !saving, !notationRestoring, !notationImporting else { throw MusicError.invalidBatch(reason: "another edit is saving") }
        if let expectedRevision, expectedRevision != document.revision {
            throw MusicError.staleRevision(expected: expectedRevision, actual: document.revision)
        }
        let instrumentTargets = operations.compactMap { operation -> MusicTrackID? in
            if case .setInstrument(let trackID, _) = operation { return trackID }
            return nil
        }
        guard instrumentTargets.isEmpty || (!isRecording && !isMIDIRecording) else {
            throw MusicError.invalidTrack(reason: IDELanguageRunText.t("请先结束录制，再更换音色。", "Finish recording before changing the instrument."))
        }
        // Raw studio edits share the same live-voice lifetime as native preset
        // controls. Observation updates the title, not the running audio graph.
        let resumeTrack = selectedTrack.flatMap { trackID in
            instrumentTargets.contains(trackID) && (isLive || previewResumeTrack == trackID) ? trackID : nil
        }
        if resumeTrack != nil { stopLive() }
        let resumeIdentity = liveIdentity
        defer { resumeLive(resumeTrack, ifIdentity: resumeIdentity) }
        saving = true
        defer { saving = false }
        cancelRender()
        stopPlayback()
        let previousRevision = document.revision
        document = try await store.commit(.init(baseRevision: document.revision, author: "native-editor", ops: operations), as: handle)
        handle = .init(sessionID: handle.sessionID, ownerToken: handle.ownerToken, baseRevision: document.revision)
        loadWaveforms()
        reconcileSelection()
        await publishSavedChange(previousRevision: previousRevision)
    }
    /// The repository commits first. File recency follows that same original;
    /// failures never turn an unsaved edit into a successful library update.
    private func publishSavedChange(previousRevision: Int64) async {
        guard document.revision != previousRevision,
              let library = try? await PersonalContentService.shared.library(),
              let location = try? await library.resolve(id), location.record.kind == .music,
              location.url.appendingPathComponent("Music").standardizedFileURL.resolvingSymlinksInPath()
                == root.standardizedFileURL.resolvingSymlinksInPath() else { return }
        do {
            try await library.markChanged(id)
            NotificationCenter.default.post(name: .floeStudioDocumentDidChange, object: id)
        } catch {
            diagnostic = IDELanguageRunText.t("作品已保存，但文件列表暂未更新。请稍后刷新。",
                "The work was saved, but its file listing could not be updated. Refresh it shortly.")
        }
    }
    func addTrack() async {
        do {
            guard !isMIDIRecording, !isRecording else {
                throw MusicError.invalidTrack(reason: IDELanguageRunText.t("请先结束录制，再添加乐器轨。", "Finish recording before adding an instrument track."))
            }
            let track = try FloeMusicCore.MusicTrack(name: IDELanguageRunText.t("乐器轨", "Instrument"),
                kind: .midi, instrument: .init(pluginID: MusicNativeBuiltins.synth))
            try await apply([.insertTrack(track)])
            selectTrack(track.id)
        } catch { diagnostic = error.localizedDescription }
    }
    func addMIDIClip(to trackID: MusicTrackID) async throws -> MusicClip {
        guard document.tracks.contains(where: { $0.id == trackID && $0.kind == .midi }) else {
            throw MusicError.invalidTrack(reason: "Select an instrument track")
        }
        let clip = try MusicClip(name: IDELanguageRunText.t("MIDI 片段", "MIDI clip"), trackID: trackID,
            offset: .init(Int64(playheadSeconds * Double(document.tempoMap.sampleRate))),
            body: .midi(.init(durationTicks: Int64(document.tempoMap.ticksPerQuarter) * 16, notes: [])))
        try await apply([.insertClip(clip)])
        selectTrack(trackID)
        selectedClip = clip.id
        return clip
    }
    func undo(redo: Bool = false) async {
        guard !saving, !notationRestoring, !notationImporting, !isRecording, !isMIDIRecording else {
            diagnostic = IDELanguageRunText.t("请先结束录制，再撤销或重做。", "Finish recording before undoing or redoing."); return
        }
        saving = true
        defer { saving = false }
        let resumeTrack = isLive ? selectedTrack : nil
        stopLive(); stopPlayback()
        let resumeIdentity = liveIdentity
        defer { resumeLive(resumeTrack, ifIdentity: resumeIdentity) }
        do {
            cancelRender()
            let previousRevision = document.revision
            document = try await (redo ? store.redo(handle) : store.undo(handle))
            handle = .init(sessionID: handle.sessionID, ownerToken: handle.ownerToken, baseRevision: document.revision)
            reconcileSelection()
            await publishSavedChange(previousRevision: previousRevision)
        } catch { diagnostic = error.localizedDescription }
    }
    func importFile(_ url: URL) async {
        let importRevision = document.revision
        do {
            guard !notationRestoring else { throw PersonalContentError.changedDocument }
            let repository = self.repository, sampleRate = document.tempoMap.sampleRate
            let imported = try await Task.detached(priority: .userInitiated) { () -> (MusicAsset, [FloeMusicCore.MusicTrack], MusicTempoMap?) in
                let access = url.startAccessingSecurityScopedResource()
                defer { if access { url.stopAccessingSecurityScopedResource() } }
                let size = try url.resourceValues(forKeys: [.fileSizeKey]).fileSize ?? Int.max
                guard size <= 128 * 1_024 * 1_024 else { throw MusicError.invalidAsset(reason: "file size limit") }
                let data = try Data(contentsOf: url, options: .mappedIfSafe)
                if ["mid", "midi"].contains(url.pathExtension.lowercased()) {
                    let imported = try MusicMIDINoteImport.read(url: url, sampleRate: sampleRate)
                    try await repository.stageAsset(.init(asset: imported.source, bytes: data))
                    return (imported.source, imported.tracks, imported.tempoMap)
                }
                let asset = try MusicAudioPreparation.inspect(url: url, projectSampleRate: sampleRate)
                try await repository.stageAsset(.init(asset: asset, bytes: data))
                let trackID = MusicTrackID()
                let clip = try MusicClip(name: asset.name, trackID: trackID, offset: .init(0),
                    body: .audio(.init(assetID: asset.id, durationSamples: asset.durationSamples.value)))
                let track = try FloeMusicCore.MusicTrack(id: trackID, name: asset.name, kind: .audio, clips: [clip])
                return (asset, [track], nil)
            }.value
            var operations: [MusicEditOp] = [.insertAsset(imported.0)]
            operations += imported.1.map(MusicEditOp.insertTrack)
            if document.tracks.isEmpty, let tempo = imported.2 { operations.append(.setTempoMap(tempo)) }
            try await apply(operations, expectedRevision: importRevision)
            if let trackID = imported.1.first?.id { selectTrack(trackID) }
            selectedClip = imported.1.first?.clips.first?.id
        } catch { diagnostic = error.localizedDescription }
    }
    struct AuthorizedImport: Sendable {
        let asset: MusicAsset
        let trackIDs: [MusicTrackID]
        let clipIDs: [MusicClipID]
        let revision: Int64
        let byteCount: Int
    }
    /// Native host only: sourceRoot/sourceReference come from the existing
    /// task workspace binding, never from a model-authored native path.
    func importAuthorizedFile(_ url: URL, sourceRoot: URL, sourceReference: String, provenance: String,
                              expectedRevision: Int64, expectedSHA256: String?, cancellation: CancellationToken,
                              validateSource: @escaping @MainActor @Sendable () async throws -> Void) async throws -> AuthorizedImport {
        let worker = Task { @MainActor in
            try await self.commitAuthorizedImport(url, sourceRoot: sourceRoot, sourceReference: sourceReference,
                provenance: provenance, expectedRevision: expectedRevision, expectedSHA256: expectedSHA256,
                cancellation: cancellation, validateSource: validateSource)
        }
        let monitor = Task {
            while !Task.isCancelled {
                if cancellation.isCancelled { worker.cancel(); return }
                do { try await Task.sleep(for: .milliseconds(50)) } catch { return }
            }
        }
        defer { monitor.cancel() }
        return try await withTaskCancellationHandler { try await worker.value } onCancel: { worker.cancel() }
    }
    private func commitAuthorizedImport(_ url: URL, sourceRoot: URL, sourceReference: String, provenance: String,
                                        expectedRevision: Int64, expectedSHA256: String?, cancellation: CancellationToken,
                                        validateSource: @escaping @MainActor @Sendable () async throws -> Void) async throws -> AuthorizedImport {
        guard !saving, !notationRestoring, !notationImporting, !isRecording, !isMIDIRecording else { throw MusicError.invalidBatch(reason: "another edit or recording is active") }
        guard expectedRevision == document.revision else { throw MusicError.staleRevision(expected: expectedRevision, actual: document.revision) }
        try cancellation.throwIfCancelled(); try await validateSource()
        let ext = url.pathExtension.lowercased()
        guard ["wav", "caf", "aif", "aiff", "mp3", "m4a", "mid", "midi"].contains(ext),
              !sourceReference.isEmpty, sourceReference.utf8.count <= 1_024 else { throw MusicError.invalidAsset(reason: "Choose a supported audio or MIDI file") }
        guard !saving, !notationRestoring, !notationImporting, !isRecording, !isMIDIRecording else { throw MusicError.invalidBatch(reason: "another edit or recording is active") }
        guard document.revision == expectedRevision else { throw MusicError.staleRevision(expected: expectedRevision, actual: document.revision) }
        saving = true; defer { saving = false }
        let destinationRoot = try MusicImportDirectory(root), sampleRate = document.tempoMap.sampleRate
        let prepared = try await personalPreviewOffMain { () -> (MusicAsset, [FloeMusicCore.MusicTrack], MusicTempoMap?, Data, PersonalPreviewFile) in
            try cancellation.throwIfCancelled(); try destinationRoot.validate()
            let source = try PersonalPreviewFile(root: sourceRoot, url: url,
                maximumBytes: ["mid", "midi"].contains(ext) ? 8 * 1_024 * 1_024 : 128 * 1_024 * 1_024)
            let bytes = try source.data(expectedSHA256: expectedSHA256,
                checkCancellation: { try cancellation.throwIfCancelled(); try Task.checkCancellation() })
            let digest = previewHash(bytes)
            // Inspect only this verified immutable copy. The parser never
            // reopens a model workspace path after the no-follow read.
            let stage = destinationRoot.url.appendingPathComponent(".music-import-" + UUID().uuidString + "." + ext)
            defer { try? FileManager.default.removeItem(at: stage) }
            try bytes.write(to: stage, options: .withoutOverwriting)
            var asset: MusicAsset; let tracks: [FloeMusicCore.MusicTrack]; let tempo: MusicTempoMap?
            if ["mid", "midi"].contains(ext) {
                let parsed = try MusicMIDINoteImport.read(url: stage, sampleRate: sampleRate)
                asset = parsed.source; tracks = parsed.tracks; tempo = parsed.tempoMap
            } else {
                asset = try MusicAudioPreparation.inspect(url: stage, projectSampleRate: sampleRate)
                let id = MusicTrackID(), clip = try MusicClip(name: url.lastPathComponent, trackID: id, offset: .init(0),
                    body: .audio(.init(assetID: asset.id, durationSamples: asset.durationSamples.value)))
                tracks = [try FloeMusicCore.MusicTrack(id: id, name: url.lastPathComponent, kind: .audio, clips: [clip])]; tempo = nil
            }
            guard asset.contentHash == digest else { throw MusicError.invalidAsset(reason: "source bytes changed during inspection") }
            asset.name = url.lastPathComponent; asset.sourceLocator = sourceReference + "/" + digest; asset.provenance = provenance
            try source.validate(); try destinationRoot.validate(); try cancellation.throwIfCancelled(); try Task.checkCancellation()
            return (asset, tracks, tempo, bytes, source)
        }
        try await validateSource(); try destinationRoot.validate(); try prepared.4.validate()
        try cancellation.throwIfCancelled(); try Task.checkCancellation()
        guard document.revision == expectedRevision else { throw MusicError.staleRevision(expected: expectedRevision, actual: document.revision) }
        if !document.tracks.isEmpty, let importedTempo = prepared.2,
           importedTempo.ticksPerQuarter != document.tempoMap.ticksPerQuarter {
            throw MusicError.invalidBatch(reason: "MIDI timebase differs from the existing project; no notes or tempo were changed")
        }
        // Same immutable blob repository and same validated CAS/undo store as
        // the existing picker import. No metadata-only insert is admitted.
        try await repository.stageAsset(.init(asset: prepared.0, bytes: prepared.3))
        try await validateSource(); try destinationRoot.validate(); try prepared.4.validate()
        try cancellation.throwIfCancelled(); try Task.checkCancellation()
        var operations: [MusicEditOp] = [.insertAsset(prepared.0)] + prepared.1.map(MusicEditOp.insertTrack)
        if document.tracks.isEmpty, let tempo = prepared.2 { operations.append(.setTempoMap(tempo)) }
        cancelRender(); stopPlayback()
        let previousRevision = document.revision
        document = try await store.commit(.init(baseRevision: expectedRevision, author: "native-task-import", ops: operations), as: handle)
        handle = .init(sessionID: handle.sessionID, ownerToken: handle.ownerToken, baseRevision: document.revision)
        if let trackID = prepared.1.first?.id { selectTrack(trackID) }
        selectedClip = prepared.1.first?.clips.first?.id
        loadWaveforms()
        await publishSavedChange(previousRevision: previousRevision)
        return .init(asset: prepared.0, trackIDs: prepared.1.map(\.id), clipIDs: prepared.1.flatMap(\.clips).map(\.id),
            revision: document.revision, byteCount: prepared.3.count)
    }
    func startLive() {
        guard !saving, !notationRestoring, !notationImporting else { return }
        guard !isLive else { return }
        stopPresetPreview()
        liveIdentity = UUID()
        do {
            guard !isRecording, let track = currentTrack, track.kind == .midi else {
                throw MusicError.invalidTrack(reason: IDELanguageRunText.t("请先选择或添加乐器轨。", "Select or add an instrument track first."))
            }
            guard let patch = track.instrument, patch.pluginID == MusicNativeBuiltins.synth,
                  MusicPresetCatalog.preset(index: patch.presetIndex) != nil else {
                throw MusicError.invalidTrack(reason: IDELanguageRunText.t("此乐器当前无法演奏，请选择一个合成音色。", "This instrument cannot be played here. Select a synthesized preset."))
            }
            let voice = try MusicLiveInstrument(ownerToken: keyboard.owner.rawValue, authority: audio,
                preset: patch.presetIndex, parameters: patch.parameters)
            try voice.start(); instrument = voice; isLive = true
        } catch { diagnostic = error.localizedDescription }
    }
    func stopLive() {
        liveIdentity = UUID(); keyboardActivation = nil
        stopPresetPreview()
        keyboard.releaseAll(reason: .panelClosed)
        instrument?.stop(); instrument = nil; isLive = false
    }
    private func resumeLive(_ trackID: MusicTrackID?, ifIdentity identity: UUID) {
        guard liveIdentity == identity, let trackID, selectedTrack == trackID, currentTrack?.kind == .midi else { return }
        startLive()
    }
    /// A late track-save callback may finish its authorized save after panel
    /// closure, but cannot activate audio or recording in a closed context.
    func activateKeyboard(recording: Bool = false) async {
        guard !saving, !notationRestoring, !notationImporting, !isRecording, !isMIDIRecording else {
            diagnostic = IDELanguageRunText.t("请先结束当前录制或保存。", "Finish recording or saving first."); return
        }
        let identity = UUID()
        keyboardActivation = identity
        defer { if keyboardActivation == identity { keyboardActivation = nil } }
        do {
            let trackID: MusicTrackID
            if let track = currentTrack, track.kind == .midi { trackID = track.id }
            else {
                let track = try FloeMusicCore.MusicTrack(name: IDELanguageRunText.t("乐器轨", "Instrument"),
                    kind: .midi, instrument: .init(pluginID: MusicNativeBuiltins.synth))
                try await apply([.insertTrack(track)], expectedRevision: document.revision)
                trackID = track.id
            }
            guard keyboardActivation == identity else { return }
            selectTrack(trackID)
            startLive()
            if recording, isLive { startMIDIRecording() }
        } catch { if keyboardActivation == identity { diagnostic = error.localizedDescription } }
    }
    func changePreset(_ value: String?) {
        guard let value, let index = Int(value), MusicPresetCatalog.preset(index: index) != nil else {
            diagnostic = IDELanguageRunText.t("此音色不可用，请从列表重新选择。", "This preset is unavailable. Choose one from the list."); return
        }
        Task { await updateInstrument(preset: index) }
    }
    /// Auditions never write an instrument or enter the keyboard recording sink.
    /// One session-owned voice and cancellation fence cover every exit path.
    func previewPreset(_ index: Int) {
        guard !saving, !notationRestoring, !notationImporting else { return }
        guard MusicPresetCatalog.preset(index: index) != nil else {
            diagnostic = IDELanguageRunText.t("此音色不可用。", "This preset is unavailable."); return
        }
        guard !saving, !isRendering, !isRecording, !isMIDIRecording else {
            diagnostic = IDELanguageRunText.t("请先结束当前录制或处理，再试听。", "Finish recording or processing before auditioning."); return
        }
        let resumeTrack = isLive ? selectedTrack : previewResumeTrack
        stopLive(); stopPlayback()
        let identity = UUID()
        let owner = keyboard.owner.rawValue + ":preset-preview:" + identity.uuidString
        diagnostic = nil
        do {
            let voice = try MusicLiveInstrument(ownerToken: owner, authority: audio, preset: index)
            try voice.start()
            previewInstrument = voice; previewPresetIndex = index
            previewIdentity = identity; previewResumeTrack = resumeTrack
            previewTask = Task { [weak self] in
                do {
                    for note: UInt8 in [60, 64, 67, 72] {
                        try Task.checkCancellation()
                        guard self?.previewIdentity == identity else { return }
                        try voice.send(.noteOn(note: note, velocity: 92, channel: 0), ownerToken: owner)
                        try await Task.sleep(for: .milliseconds(180))
                        try voice.send(.noteOff(note: note, channel: 0), ownerToken: owner)
                        try await Task.sleep(for: .milliseconds(60))
                    }
                    try await Task.sleep(for: .milliseconds(350))
                    guard let self, self.previewIdentity == identity else { return }
                    let resume = self.previewResumeTrack
                    self.stopPresetPreview()
                    if let resume, self.selectedTrack == resume { self.startLive() }
