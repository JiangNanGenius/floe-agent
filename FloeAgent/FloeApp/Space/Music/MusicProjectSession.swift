    func toggleDJ(_ slot: MusicDJSession.DeckSlot? = nil) {
        if slot == nil, djIsActive { stopDJ(); return }
        guard !isRecording, !isMIDIRecording, !isRendering, !djLoading,
              djCapturePhase != .starting, djCapturePhase != .finishing else { return }
