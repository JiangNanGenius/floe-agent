    func readVideoScopes(at seconds: Double) async throws -> MediaVideoScopeSnapshot {
        let frozen = document, generation = UUID()
        scopeReadGeneration = generation
        guard frozen.kind == .video,let canvas = frozen.canvas,seconds.isFinite,seconds>=0,seconds<frozen.trackGraph.totalDurationSeconds else { throw MediaV2CommandError.invalidInput }
        let plan = try MediaPreparedVideoDocumentAdapter.resolve(frozen,assetURLs:resolvedAssets(),includeAudio:false)
        let scale = min(1,512/Double(max(canvas.width,canvas.height)))
        let settings = try PreparedVideoOutputSettings(width:max(2,Int(Double(canvas.width)*scale)/2*2),height:max(2,Int(Double(canvas.height)*scale)/2*2),frameRate:plan.frameRate)
        let cancellation = PreparedVideoCancellation()
        let frame = try await withTaskCancellationHandler {
            try await frameRenderer.renderFrame(plan:plan,at:.init(seconds:seconds,timescale:plan.timeScale),settings:settings,cancellation:cancellation)
        } onCancel: { cancellation.cancel() }
        try Task.checkCancellation()
        let worker = Task.detached(priority:.userInitiated) {
            try MediaVideoScopeSnapshot.measure(frame.image,documentID:frozen.id,revision:frozen.revision,timelineSeconds:seconds)
        }
        let result = try await withTaskCancellationHandler { try await worker.value } onCancel: { worker.cancel() }
        try Task.checkCancellation()
        guard document.revision == frozen.revision else { throw MediaPreparedCoreError.documentChanged }
        if scopeReadGeneration == generation { videoScopes = result }
        return result
    }
    func refreshPreview() {
        previewTask?.cancel()
        let frozen = project, position = playhead
        previewTask = Task { [weak self] in
            guard let self else { return }
            do {
                try await Task.sleep(for: .milliseconds(60))
                let assets = try resolvedAssets()
                let image: CGImage
                if frozen.kind == .image {
                    let canvas = frozen.canvas ?? .init(width: 1600, height: 1200)
                    image = try await imageRenderer.render(project: frozen, canvas: CGSize(width: canvas.width, height: canvas.height), resolveAsset: { assets[$0] }, previewMaxEdge: 2048)
                } else {
                    guard duration > 0, Self.hasVisibleClips(frozen.prepared!.trackGraph) else { preview = nil; return }
                    let plan = try MediaPreparedVideoDocumentAdapter.resolve(frozen.prepared!, assetURLs: assets, includeAudio: false)
                    let canvas = plan.canvas
                    let scale = min(1, 1280 / Double(max(canvas.width, canvas.height)))
                    let settings = try PreparedVideoOutputSettings(width: max(2, Int(Double(canvas.width) * scale) / 2 * 2), height: max(2, Int(Double(canvas.height) * scale) / 2 * 2), frameRate: plan.frameRate)
                    let frame = min(max(0, plan.frameRate.frameIndex(for: try .init(seconds: position, timescale: plan.timeScale), rounding: .down)), max(0, plan.frameRate.frameIndex(for: plan.duration, rounding: .up) - 1))
                    image = try await frameRenderer.renderFrame(plan: plan, frameIndex: frame, settings: settings).image
                }
                guard !Task.isCancelled, project.id == frozen.id, project.revision == frozen.revision else { return }
                preview = image
            } catch {
                if !Task.isCancelled { preview = nil; diagnostic = error.localizedDescription }
            }
        }
    }
