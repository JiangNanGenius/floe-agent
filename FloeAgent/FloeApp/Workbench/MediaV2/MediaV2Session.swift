    struct ImportedAsset { let commit: MediaPreparedCommit; let asset: MediaAssetReference }
    /// URL is supplied only by a system picker or the verified native host.
    /// No model-authored host URL is accepted at the callable boundary.
    func importAuthorizedFile(_ url: URL, expectedRevision: Int64, expectedSHA256: String? = nil,
                              actor: MediaPreparedActorKind = .user, cancellation: CancellationToken? = nil,
                              validateSource: @MainActor () async throws -> Void = {}) async throws -> ImportedAsset {
        guard expectedRevision == document.revision else { throw MediaPreparedCoreError.documentChanged }
        let scope = MediaV2ImportScope(token: cancellation)
        var admitted = false
        try scope.validate(); try await validateSource()
        do {
            let reference = try await stage(url, importScope: scope)
            if let expectedSHA256, reference.contentHash != expectedSHA256 { throw MediaPreparedCoreError.conflict("import source SHA256 changed") }
            var actions: [MediaPreparedAction] = [.insertAsset(reference)]
            if project.kind == .image {
                guard reference.kind == .image else { throw PersonalContentError.invalidProject }
                let layer = MediaPreparedLayer(name: reference.originalName, content: .raster(.init(source: .asset(reference.id))))
                actions.append(.insertLayer(layer: layer, parentID: nil, index: nil)); selectedLayerID = layer.id
            } else {
                let kind: MediaPreparedTrackKind = reference.kind == .audio ? .audio : .visual
                let track = document.trackGraph.tracks.first { $0.id == selectedTrackID && $0.kind == kind }
                    ?? document.trackGraph.tracks.first { $0.kind == kind }
                    ?? MediaPreparedTrack(kind: kind, name: reference.originalName)
                if !document.trackGraph.tracks.contains(where: { $0.id == track.id }) { actions.append(.insertTrack(track: track, index: nil)) }
                let seconds = reference.kind == .image ? 5 : reference.metadata?.durationSeconds ?? 0
                guard seconds > 0 else { throw PersonalContentError.invalidProject }
                let range = try Self.range(start: playhead, duration: seconds)
                let clip = MediaPreparedClip(assetID: reference.id, timelineRange: range, sourceRange: try Self.range(start: 0, duration: seconds), isMuted: reference.kind == .video && (reference.metadata?.audioTracks ?? 0) > 0)
                actions.append(.insertClip(trackID: track.id, clip: clip, index: nil)); selectedTrackID = track.id; selectedClipID = clip.id
                if reference.kind == .video, (reference.metadata?.audioTracks ?? 0) > 0 {
                    let audio = try await extractAudio(reference, importScope: scope)
                    actions.append(.insertAsset(audio))
                    let track = MediaPreparedTrack(kind: .audio, name: reference.originalName + WorkbenchText.t(" · 原声", " · source audio"))
                    actions.append(.insertTrack(track: track, index: nil))
                    actions.append(.insertClip(trackID: track.id, clip: .init(assetID: audio.id, timelineRange: range, sourceRange: try Self.range(start: 0, duration: seconds), sourceVisualClipID: clip.id), index: nil))
                }
            }
            try scope.validate()
            try await validateSource()
            try scope.validate()
            admitted = true
            let commit = try await apply(actions.map { .init(action: $0) }, expectedRevision: expectedRevision, actor: actor, didCommit: { scope.didCommit() })
            return .init(commit: commit, asset: reference)
        } catch {
            if admitted {
                // A reload/stop can fail after the atomic store commit. Only
                // delete fresh assets proven unreferenced by durable state.
                do {
                    if let durable = try await store.loadProject(id: id), durable.prepared != nil { scope.retainReferenced(in: durable) }
                    else { scope.didCommit() }
                } catch { scope.didCommit() }
            }
            throw error
        }
    }
    private func stage(_ source: URL, importScope: MediaV2ImportScope? = nil, ephemeralSource: Bool = false) async throws -> MediaAssetReference {
        let (staged, reference) = try await MediaV2ImportIO.stage(source, root: root, token: importScope?.token, ephemeralSource: ephemeralSource)
        if let importScope { importScope.add(staged) } else { staged.keepCommitted() }
        return reference
    }
    private func extractAudio(_ reference: MediaAssetReference, importScope: MediaV2ImportScope? = nil) async throws -> MediaAssetReference {
        let canonical = root.resolvingSymlinksInPath().standardizedFileURL
        let url = (reference.relativePath.hasPrefix("/") ? URL(fileURLWithPath: reference.relativePath) : canonical.appendingPathComponent(reference.relativePath)).resolvingSymlinksInPath().standardizedFileURL
        guard url.path.hasPrefix(canonical.path + "/") else { throw PersonalContentError.outsideLibrary }
        let temporary = try MediaV2ImportTemporaryFile(root: root)
        let destination = temporary.url
        defer { withExtendedLifetime(temporary) {} }
        guard let export = AVAssetExportSession(asset: AVURLAsset(url: url), presetName: AVAssetExportPresetAppleM4A) else { throw PersonalContentError.invalidProject }
        try await export.export(to: destination, as: .m4a)
        let staged = try await stage(destination, importScope: importScope, ephemeralSource: true)
        return staged
    }
    func editableSourceAudio(for clipID: UUID) async throws -> (track: MediaPreparedTrack, clip: MediaPreparedClip) {
        func linked() throws -> (track: MediaPreparedTrack, clip: MediaPreparedClip)? {
            let matches = document.trackGraph.tracks.filter { $0.kind == .audio }.flatMap { track in
                track.clips.filter { $0.sourceVisualClipID == clipID }.map { (track:track,clip:$0) }
            }
            guard matches.count <= 1 else {
                throw MediaPreparedCoreError.invalidOperation(WorkbenchText.t("此视频关联了多段音频，请直接选择要编辑的音频片段。", "This video has multiple linked audio clips. Select the audio clip to edit."))
            }
            return matches.first
        }
        if let result = try linked() { return result }
        guard !processingTool,!saving,let visual = document.trackGraph.clip(id:clipID),visual.track.kind == .visual,!visual.track.isLocked else { throw MediaV2CommandError.missingSelection }
        processingTool = true;defer { processingTool = false }
        try await prepareVideoSourceAudio(targetClipID:clipID)
        guard let result = try linked() else { throw MediaV2CommandError.missingSelection }
        return result
    }
    private func prepareVideoSourceAudio(targetClipID: UUID? = nil) async throws {
        guard project.kind == .video else { return }
        let frozen = document
        let sources = try resolvedAssets()
        var actions: [MediaPreparedAction] = []
        var staged: [UUID: MediaAssetReference] = [:]
        for track in frozen.trackGraph.tracks where track.kind == .visual {
            for clip in track.clips where targetClipID.map({ $0 == clip.id }) ?? !clip.isMuted {
                guard let assetID = clip.assetID, let asset = frozen.asset(assetID), asset.kind == .video else { continue }
                guard let url = sources[assetID] else { throw PersonalContentError.missingDocument }
                let hasAudio = try await AVURLAsset(url: url).loadTracks(withMediaType: .audio).isEmpty == false
                guard hasAudio else { continue }
                let source: MediaAssetReference
                if let existing = staged[assetID] { source = existing }
                else { source = try await extractAudio(asset); staged[assetID] = source; actions.append(.insertAsset(source)) }
                var visual = clip; visual.isMuted = true
                actions.append(.replaceClip(trackID: track.id, clipID: clip.id, expectedRevision: clip.revision, clip: visual))
                let audio = MediaPreparedTrack(kind: .audio, name: asset.originalName + WorkbenchText.t(" · 原声", " · source audio"), isMuted: track.isMuted, volume: track.volume)
                actions.append(.insertTrack(track: audio, index: nil))
                var sound = clip; sound.id = UUID(); sound.assetID = source.id; sound.isMuted = clip.isMuted; sound.revision = 0; sound.sourceVisualClipID = clip.id
                sound.videoGrade = nil;sound.chromaKey = nil;sound.blendMode = nil;sound.visualOpacity = nil
                actions.append(.insertClip(trackID: audio.id, clip: sound, index: nil))
            }
        }
        if !actions.isEmpty { _ = try await apply(actions.map { .init(action: $0) }, expectedRevision: frozen.revision) }
    }
    static func time(_ seconds: Double) throws -> MediaRationalTime {
        guard seconds.isFinite, abs(seconds) <= 100_000 else { throw PersonalContentError.invalidProject }
        return try .init(value: Int64((seconds * 90_000).rounded()), timescale: 90_000)
    }
    static func range(start: Double, duration: Double) throws -> MediaTimeRange { try .init(start: time(start), duration: time(duration)) }
    static func hasVisibleClips(_ graph: MediaPreparedTrackGraph) -> Bool {
        graph.tracks.contains { track in
            track.kind == .visual && !track.isMuted && track.clips.contains { $0.timelineRange.durationSeconds > 0 }
        }
    }
    func export(options: ImageExportOptions? = nil) {
        guard !rendering, !processingTool, !saving else { return }
        let imageOptions = options ?? imageExportOptions
        rendering = true; diagnostic = nil; exportError = nil; exportProgress = nil; exportedFile = nil
        let token = PreparedVideoCancellation(); cancellation = token
        exportTask = Task { [self] in
            defer { rendering = false; exportTask = nil; cancellation = nil }
            do {
                if project.kind == .video {
                    guard Self.hasVisibleClips(document.trackGraph) else { throw PreparedVideoError.emptyTimeline }
                }
                try await prepareVideoSourceAudio()
                let frozen = project
                let urls = try resolvedAssets()
                let folder = root.appendingPathComponent("Exports").appendingPathComponent(UUID().uuidString)
                try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
                let stem = imageOptions.fileName.replacingOccurrences(of: "/", with: "-").replacingOccurrences(of: "\\", with: "-")
                    .components(separatedBy: .controlCharacters).joined().trimmingCharacters(in: CharacterSet(charactersIn: ". ").union(.whitespacesAndNewlines))
                let file = folder.appendingPathComponent((frozen.kind == .image ? (stem.isEmpty ? "export" : String(stem.prefix(100))) : "export") + "." + (frozen.kind == .image ? imageOptions.format.fileExtension : "mp4"))
                if frozen.kind == .image {
                    _ = try await imageRenderer.exportImage(project: frozen, options: imageOptions, resolveAsset: { urls[$0] }, destination: file)
                } else {
                    let canvas = frozen.canvas!
                    _ = try await videoDelivery.export(document: frozen.prepared!, assetURLs: urls,
                        options: .init(codec: canvas.videoColorProfile?.isHDR == true ? .hevc : .h264,width: canvas.width, height: canvas.height, frameRate: frozen.prepared!.trackGraph.frameRate?.seconds ?? 30,colorProfile: canvas.videoColorProfile), destination: file, cancellation: token) { [weak self] value in
                            Task { @MainActor in self?.exportProgress = value }
                        }
                }
                try token.check()
                guard project.id == frozen.id, project.revision == frozen.revision else { throw MediaPreparedCoreError.documentChanged }
                exportedFile = file
            } catch {
                exportError = error
                if !Task.isCancelled { diagnostic = Self.exportFailureMessage(error) }
            }
        }
    }
    func cancelExport() { cancellation?.cancel(); exportTask?.cancel() }
    func exportAndWait() async throws -> URL {
        guard !rendering, !processingTool, !saving else { throw MediaV2CommandError.exportInProgress }
        export()
        let task = exportTask, token = cancellation
        await withTaskCancellationHandler { await task?.value } onCancel: { token?.cancel(); task?.cancel() }
        try Task.checkCancellation()
        if let error = exportError { throw error }
        guard let file = exportedFile else { throw MediaV2CommandError.missingExport }
        return file
    }
    private static func exportFailureMessage(_ error: any Error) -> String {
        if error as? PreparedVideoError == .emptyTimeline {
            return WorkbenchText.t("时间线还没有可导出的画面。请先加入并显示视频或图片片段。", "The timeline has no visible frames to export. Add a video or image clip and make it visible.")
        }
        return error.localizedDescription
    }
