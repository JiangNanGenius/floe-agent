#!/usr/bin/env python3
"""Fixture generator entry point (SUPERSEDED implementation).

The original pure-Python generator built wire bytes from a hand-maintained
layout model and disagreed with the real C structs (cmd_close 12 vs 16,
resp_open_ok 12 vs 16, resp_mmap 20 vs 24, wrong v4l2_buffer offsets).
Fixtures are now generated by scripts/gen_fixtures_c.c, which fills the
genuine driver/protocol.h structs against the pinned 6.12.107 UAPI headers.

This script now only locates/invokes the compiled generator. Build it first:

  cc -I "$HDRS/include" -I driver -o <scratch>/bin/gen_fixtures scripts/gen_fixtures_c.c

where $HDRS is a `make headers_install INSTALL_HDR_PATH=...` output of the
pinned kernel tree (per scripts/build_module.py preparation).
"""
import os, subprocess, sys
from pathlib import Path

STAGE = Path(__file__).resolve().parents[1]
DEFAULT_BIN = Path.home() / "Library/Caches/CodexBuild/FloeAgent/virtual-video/bin/gen_fixtures"

def main():
    exe = Path(os.environ.get("FVM_GEN_FIXTURES", DEFAULT_BIN))
    if not exe.exists():
        raise SystemExit(
            f"compiled generator not found: {exe}\n"
            "build scripts/gen_fixtures_c.c first (see that file's header comment)")
    r = subprocess.run([str(exe), str(STAGE / "fixtures")])
    raise SystemExit(r.returncode)

if __name__ == "__main__":
    main()
