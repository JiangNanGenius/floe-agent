#!/usr/bin/env python3
"""Install Floe's bundled pure-Python preset packages.

Reads scripts/python_bundled_packages.lock.json (generated by
pin_python_bundled_packages.py) and unpacks each pinned py3-none-any wheel
into the app's bundled site-packages at build time.

The lock is authoritative and offline: this script never resolves versions.
Usage:
    python3 install_python_bundled_packages.py [--check] [--site-packages PATH]

--check verifies the lock, downloads and digests without touching the tree.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import re
import stat
import tempfile
from urllib.parse import urlparse
import sys
import urllib.request
import zipfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
LOCK_PATH = Path(__file__).resolve().parent / "python_bundled_packages.lock.json"
DEFAULT_SITE_PACKAGES = (
    REPO_ROOT / "FloeAgent" / "FloeApp" / "Resources" / "python" / "lib" / "python3.13" / "site-packages"
)


def load_lock() -> list[dict]:
    if not LOCK_PATH.exists():
        raise SystemExit(f"missing lock file: {LOCK_PATH}")
    with LOCK_PATH.open() as handle:
        payload = json.load(handle)
    packages = payload.get("packages")
    if not isinstance(packages, list):
        raise SystemExit("lock file must contain a 'packages' array")
    seen = set()
    for entry in packages:
        for key in ("name", "version", "url", "sha256"):
            if not entry.get(key):
                raise SystemExit(f"lock entry missing {key}: {entry!r}")
        name = re.sub(r"[-_.]+", "-", entry["name"]).lower()
        if name in seen:
            raise SystemExit("duplicate package in lock: " + name)
        seen.add(name)
        parsed = urlparse(entry["url"])
        if parsed.scheme != "https" or parsed.hostname != "files.pythonhosted.org" or not parsed.path.endswith("-none-any.whl"):
            raise SystemExit("lock must use pinned pure-Python wheels from files.pythonhosted.org")
        if not re.fullmatch(r"[0-9a-f]{64}", entry["sha256"]):
            raise SystemExit("invalid SHA-256 in lock")
    return packages


def download(entry: dict, cache_dir: Path) -> Path:
    cache_dir.mkdir(parents=True, exist_ok=True)
    filename = entry["url"].rsplit("/", 1)[-1]
    destination = cache_dir / filename
    if destination.exists():
        if digest(destination) == entry["sha256"]:
            return destination
        destination.unlink()
    with urllib.request.urlopen(entry["url"], timeout=60) as response:
        destination.write_bytes(response.read())
    actual = digest(destination)
    if actual != entry["sha256"]:
        destination.unlink()
        raise SystemExit(f"sha256 mismatch for {entry['name']}: {actual} != {entry['sha256']}")
    return destination


def digest(path: Path) -> str:
    hasher = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            hasher.update(chunk)
    return hasher.hexdigest()


def validate_wheel(wheel: Path) -> None:
    with zipfile.ZipFile(wheel) as archive:
        members = archive.infolist()
        if len(members) > 20000 or sum(m.file_size for m in members) > 256 * 1024 * 1024:
            raise SystemExit("wheel exceeds extraction limits")
        seen = set()
        for member in members:
            path = Path(member.filename)
            if path.is_absolute() or ".." in path.parts or "\\" in member.filename or member.filename in seen:
                raise SystemExit("unsafe or duplicate wheel member")
            seen.add(member.filename)
            if stat.S_ISLNK(member.external_attr >> 16):
                raise SystemExit("wheel contains a symbolic link")
            if path.suffix.lower() in {".so", ".dylib", ".a", ".dll", ".exe"}:
                raise SystemExit("pure-Python wheel contains a native artifact")
            if not member.is_dir():
                with archive.open(member) as source:
                    if source.read(4) in {b"\x7fELF", b"\xcf\xfa\xed\xfe", b"\xfe\xed\xfa\xcf", b"\xce\xfa\xed\xfe", b"\xfe\xed\xfa\xce", b"\xca\xfe\xba\xbe", b"\xbe\xba\xfe\xca"}:
                        raise SystemExit("pure-Python wheel contains a native executable")


def install(wheel: Path, site_packages: Path) -> int:
    validate_wheel(wheel)
    installed = 0
    site_packages.mkdir(parents=True, exist_ok=True)
    root = site_packages.resolve()
    with zipfile.ZipFile(wheel) as archive:
        # Validate all destinations before any writes, including existing symlinks.
        for member in archive.infolist():
            target = site_packages / member.filename
            if not target.resolve().is_relative_to(root):
                raise SystemExit("wheel destination escapes site-packages")
        for member in archive.infolist():
            if member.is_dir():
                continue
            target = site_packages / member.filename
            target.parent.mkdir(parents=True, exist_ok=True)
            with archive.open(member) as source, target.open("wb") as output:
                shutil.copyfileobj(source, output)
            installed += 1
    return installed


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--site-packages", type=Path, default=DEFAULT_SITE_PACKAGES)
    args = parser.parse_args()

    packages = load_lock()
    cache_dir = Path(__file__).resolve().parent / ".wheel-cache"
    total_files = 0
    for entry in packages:
        wheel = download(entry, cache_dir)
        validate_wheel(wheel)
        if args.check:
            print(f"ok {entry['name']}=={entry['version']} sha256={entry['sha256'][:12]}…")
            continue
        args.site_packages.mkdir(parents=True, exist_ok=True)
        files = install(wheel, args.site_packages)
        total_files += files
        print(f"installed {entry['name']}=={entry['version']} ({files} files)")
    if args.check:
        print(f"lock verified: {len(packages)} packages")
    else:
        print(f"bundled {len(packages)} packages, {total_files} files -> {args.site_packages}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
