"""Generate original, deterministic RPG Maker fixture art and JSON data.

No proprietary RTP/Enterbrain artwork is used. Every pixel is generated by
this script. Run from the package root:

    python3 Tools/generate_fixtures.py
"""
from pathlib import Path
import json
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
FIX = ROOT / "Tests" / "FloeRPGTilesetKitTests" / "Fixtures"


def color(seed: int, cell: int):
    h = (seed * 1103515245 + cell * 12345 + 0x9E3779B9) & 0xFFFFFFFF
    r = 36 + (h & 0x7F)
    g = 36 + ((h >> 8) & 0x7F)
    b = 36 + ((h >> 16) & 0x7F)
    return (r, g, b, 255)


def png_bytes(width: int, height: int, pixel):
    rows = []
    for y in range(height):
        row = bytearray([0])
        for x in range(width):
            row.extend(pixel(x, y))
        rows.append(bytes(row))
    raw = b"".join(rows)
    def chunk(tag, data):
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def write_ordinary(path: Path, width: int, height: int, tile: int, seed: int):
    def pixel(x, y):
        cell = (y // tile) * (width // tile) + (x // tile)
        r, g, b, a = color(seed, cell)
        border = (x % tile == 0) or (y % tile == 0) or (x % tile == tile - 1) or (y % tile == tile - 1)
        if border:
            return (max(0, r - 30), max(0, g - 30), max(0, b - 30), a)
        return (r, g, b, a)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png_bytes(width, height, pixel))


def write_autotile(path: Path, width: int, height: int, tile: int, seed: int, mini: int):
    def pixel(x, y):
        mx, my = x // mini, y // mini
        r, g, b, a = color(seed, my * (width // mini) + mx)
        border = (x % mini == 0) or (y % mini == 0) or (x % mini == mini - 1) or (y % mini == mini - 1)
        if border:
            return (max(0, r - 24), max(0, g - 24), max(0, b - 24), a)
        return (r, g, b, a)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png_bytes(width, height, pixel))


def write_character(path: Path, width: int, height: int, frame_w: int, frame_h: int, seed: int):
    def pixel(x, y):
        cell = (y // frame_h) * (width // frame_w) + (x // frame_w)
        r, g, b, a = color(seed, cell)
        # transparent-ish margins so the character frame is distinguishable
        if x % frame_w < 3 or y % frame_h < 3:
            return (r, g, b, 90)
        return (r, g, b, 255)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png_bytes(width, height, pixel))


def write_json(path: Path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, separators=(",", ":"), ensure_ascii=False), encoding="utf-8")


# --- XP ---------------------------------------------------------------------

def xp():
    d = FIX / "xp-project"
    write_ordinary(d / "Graphics/Tilesets/FloeXP_Tiles.png", 256, 512, 32, 11)
    for i in range(1, 8):
        write_autotile(d / f"Graphics/Autotiles/FloeXP_A{i}.png", 96, 128, 32, 100 + i, 16)
    write_character(d / "Graphics/Characters/FloeHero.png", 512, 384, 32, 48, 7)


# --- VX / Ace ---------------------------------------------------------------

def vx_like(name: str, prefix: str, ext: str, seed: int):
    d = FIX / name
    sizes = {
        "A1": (512, 384), "A2": (512, 384), "A3": (512, 256),
        "A4": (512, 480), "A5": (256, 512),
        "B": (512, 512), "C": (512, 512), "D": (512, 512), "E": (512, 512),
    }
    for key, (w, h) in sizes.items():
        if key.startswith("A"):
            write_autotile(d / f"Graphics/System/{prefix}_{key}.png", w, h, 32, seed + int(key[1]), 16)
        else:
            write_ordinary(d / f"Graphics/System/{prefix}_{key}.png", w, h, 32, seed + ord(key))
    write_character(d / "Graphics/Characters/FloeHero.png", 384, 256, 32, 32, seed + 7)
    return d


# --- MV / MZ ----------------------------------------------------------------

def mv_like(name: str, prefix: str, tilesets_filename: str, seed: int):
    d = FIX / name
    sizes = {
        "A1": (768, 576), "A2": (768, 576), "A3": (768, 384),
        "A4": (768, 720), "A5": (384, 768),
        "B": (768, 768), "C": (768, 768), "D": (768, 768), "E": (768, 768),
    }
    for key, (w, h) in sizes.items():
        if key.startswith("A"):
            write_autotile(d / f"img/tilesets/{prefix}_{key}.png", w, h, 48, seed + int(key[1]), 24)
        else:
            write_ordinary(d / f"img/tilesets/{prefix}_{key}.png", w, h, 48, seed + ord(key))
    write_character(d / "img/characters/FloeHero.png", 576, 384, 48, 48, seed + 7)
    names = [f"{prefix}_{key}" for key in ["A1", "A2", "A3", "A4", "A5", "B", "C", "D", "E"]]
    tilesets = [None, {
        "id": 1, "mode": 0, "name": f"Floe {prefix}",
        "note": "Original synthetic fixture. No RTP content.",
        "tilesetNames": names,
        "flags": [0] * 8192,
        "floeUnknown": {"keep": True},
    }]
    write_json(d / "data" / tilesets_filename, tilesets)


