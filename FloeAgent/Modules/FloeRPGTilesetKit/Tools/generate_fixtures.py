def mv_map(engine_prefix: str):
    width, height = 12, 10
    data = [0] * (width * height * 6)

    def put(z, x, y, gid):
        data[(z * height + y) * width + x] = gid

    # z0 ground: A2 grass (kind 16) shapes, A1 water/waterfall, A5, B.
    ground = [
        (0, 0, 2816 + 0 * 48 + 47), (1, 0, 2816 + 0 * 48 + 0),
        (2, 0, 2816 + 0 * 48 + 8), (3, 0, 2816 + 0 * 48 + 16),
        (4, 0, 2048 + 0 * 48 + 47), (5, 0, 2048 + 5 * 48 + 0),
        (6, 0, 1536 + 0), (7, 0, 1536 + 9), (8, 0, 1), (9, 0, 257), (10, 0, 513), (11, 0, 769),
    ]
    for i in range(12, width * height):
        x, y = i % width, i // width
        ground.append((x, y, 2816 + ((x + y) % 32) * 48 + 47))
    for x, y, gid in ground:
        put(0, x, y, gid)

    # z1 overlay: A3 roofs and A4 walls plus A5.
    overlays = [
        (0, 0, 4352 + 0 * 48 + 0), (1, 0, 4352 + 0 * 48 + 8),
        (0, 1, 5888 + 0 * 48 + 47), (1, 1, 2048 + 88 * 48 + 0),
        (2, 1, 1536 + 16), (3, 1, 2), (4, 1, 258),
    ]
    for x, y, gid in overlays:
        put(1, x, y, gid)
    # z2 upper layer
    for x in range(4):
        put(2, x, 2, 2816 + (3) * 48 + 47)
    put(3, 2, 2, 513 + 3)
    # z3 top layer (MV/MZ only)
    put(3, 5, 5, 769 + 7)
    # z4 shadow bits / z5 region ids are preserved but not tile layers.
    for i in range(width * height):
        if i % 7 == 0:
            data[4 * width * height + i] = 0x0F
        data[5 * width * height + i] = (i % 5) + 1
    events = [None, {
        "id": 1, "name": "Hero", "note": "fixture event", "x": 2, "y": 2,
        "floeUnknown": "keep-event",
        "pages": [{
            "image": {"characterName": "FloeHero", "characterIndex": 0,
                      "direction": 2, "pattern": 1, "tileId": 0},
            "moveRoute": {"repeat": True, "skippable": False, "wait": True, "list": []},
            "list": [{"code": 0, "indent": 0, "parameters": []}],
        }],
    }, {
        "id": 2, "name": "Guard", "x": 8, "y": 6, "pages": [{
            "image": {"characterName": "FloeHero", "characterIndex": 1,
                      "direction": 4, "pattern": 1, "tileId": 0},
            "list": [{"code": 101, "indent": 0, "parameters": ["", 0, 0, 2]}],
        }],
    }]
    return {
        "autoplayBgm": False, "autoplayBgs": False, "battleback1Name": "",
        "battleback2Name": "", "bgm": {"name": "", "volume": 90, "pitch": 100, "pan": 0},
        "bgs": {"name": "", "volume": 90, "pitch": 100, "pan": 0},
        "disableDashing": False, "displayName": "Floe Fixture", "encounterList": [],
        "encounterStep": 30, "height": height, "note": "Original synthetic map.",
        "parallaxLoopX": False, "parallaxLoopY": False, "parallaxName": "",
        "parallaxShow": True, "parallaxSx": 0, "parallaxSy": 0, "scrollType": 0,
        "specifyBattleback": False, "tilesetId": 1, "width": width, "data": data,
        "events": events, "floeUnknown": "keep-map",
    }


