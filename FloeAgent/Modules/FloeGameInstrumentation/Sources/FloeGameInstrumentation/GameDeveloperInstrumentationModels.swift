public struct GameDeveloperInstrumentationLimits: Sendable, Equatable {
    public let maximumMetadataBytes: Int
    public let maximumDependencyScanFiles: Int
    public let maximumDependencyScanBytes: Int
    public let maximumSourceBundleBytes: Int

    public init(maximumMetadataBytes: Int = 1_048_576,
                maximumDependencyScanFiles: Int = 500,
                maximumDependencyScanBytes: Int = 8 * 1_048_576,
                maximumSourceBundleBytes: Int = 8 * 1_048_576) throws {
        guard (1_024...8_388_608).contains(maximumMetadataBytes),
              (1...5_000).contains(maximumDependencyScanFiles),
              (0...67_108_864).contains(maximumDependencyScanBytes),
              (1_024...67_108_864).contains(maximumSourceBundleBytes) else {
            throw GameDeveloperInstrumentationError.limitExceeded("invalid limits")
        }
        self.maximumMetadataBytes = maximumMetadataBytes
        self.maximumDependencyScanFiles = maximumDependencyScanFiles
        self.maximumDependencyScanBytes = maximumDependencyScanBytes
        self.maximumSourceBundleBytes = maximumSourceBundleBytes
    }
}

public enum GameDeveloperInstrumentationFileKind: String, Codable, Sendable {
    /// Exact reviewed helper source installed byte-for-byte.
    case helperSource
    /// Existing project file patched deterministically; unknown content is kept.
    case projectPatch
    /// Deterministic metadata generated by the installer (for example a Cocos
    /// `.meta` file). It is created only when absent and never overwrites a
    /// different existing file.
    case generatedFile
}

public enum GameDeveloperInstrumentationFileAction: String, Codable, Sendable {
    case create
    case patch
    case unchanged
}

/// One exact file effect in a previewed plan. `outputData` is repository data
/// derived from the reviewed resource or a bounded project.godot patch; it is
/// never model-authored content.
public struct GameDeveloperProjectInstrumentationFile: Sendable, Equatable, Identifiable {
    public let path: GameRelativePath
    public let kind: GameDeveloperInstrumentationFileKind
    public let action: GameDeveloperInstrumentationFileAction
    public let templateResource: String
    public let templateSHA256: String
    public let existingSHA256: String?
    public let outputSHA256: String
    public let outputBytes: Int
    public let outputData: Data

    public var id: String { path.value }
    public var changed: Bool { action != .unchanged }
}

public struct GameDeveloperInstrumentationDiagnostic: Sendable, Equatable, Identifiable {
    public enum Severity: String, Codable, Sendable {
        case information
        case warning
    }

    public let severity: Severity
    public let code: String
    public let path: GameRelativePath?
    public let message: String
    public let messageZhHans: String

    public var id: String { code + ":" + (path?.value ?? "") }

    public init(severity: Severity, code: String, path: GameRelativePath? = nil,
                message: String, messageZhHans: String) {
        self.severity = severity
        self.code = String(code.prefix(128))
        self.path = path
        self.message = String(message.prefix(2_048))
        self.messageZhHans = String(messageZhHans.prefix(2_048))
    }
}

public struct GameDeveloperGodotAutoloadPlan: Sendable, Equatable {
    public let section: String
    public let key: String
    public let value: String
    public let line: String
    public let previousValue: String?
    public let changed: Bool
    public let lineEnding: String
    public let hadBOM: Bool
}

/// How a GDevelop project is expected to reach a playable copy. Source JSON is
/// exported by the official SDK; an imported playable export is decorated in
/// its private run copy. The enum is explicit so callers never confuse the two
/// shapes or promise a rebuild that is not needed.
public enum GameDeveloperInstrumentationExportHandling: String, Codable, Sendable {
    case notApplicable
    case sourceRequiresExport
    case alreadyExportedPlayable
    case sourceWithExistingExport
}

/// An explicit Cocos scene choice. The scene id is the Creator asset UUID from
/// the scene mirror; the path is project-relative. `isStartScene` comes from
/// actual project build metadata, never a guessed first file.
public struct GameDeveloperInstrumentationSceneChoice: Codable, Equatable, Sendable, Identifiable {
    public let id: String
    public let path: GameRelativePath
    public let name: String
    public let isStartScene: Bool

    public init(id: String, path: GameRelativePath, name: String, isStartScene: Bool) {
        self.id = id
        self.path = path
        self.name = name
        self.isStartScene = isStartScene
    }
}

/// The scene actually previewed/applied. For engines without scenes this is
/// nil.
public struct GameDeveloperInstrumentationScene: Codable, Equatable, Sendable {
    public let id: String
    public let path: GameRelativePath
    public let name: String
    public let isStartScene: Bool

    public init(choice: GameDeveloperInstrumentationSceneChoice) {
        self.id = choice.id
        self.path = choice.path
        self.name = choice.name
        self.isStartScene = choice.isStartScene
    }
}

public struct GameDeveloperInstrumentationDormancy: Sendable, Equatable {
    public let hostObjectName: String
    public let gated: Bool
    public let evidence: [String]
    public let productionBehavior: String
    public let productionBehaviorZhHans: String
}

public struct GameDeveloperProjectInstrumentationPlan: Sendable, Equatable {
    public let schemaVersion: Int
    public let planID: UUID
    public let engine: GameEngineID
    public let catalogVersion: String
    public let descriptor: GameDeveloperEngineDescriptor
    public let context: GameProjectContext
    public let gameRoot: GameRelativePath?
    public let gameRootPath: String
    public let engineVersion: String
    public let files: [GameDeveloperProjectInstrumentationFile]
    public let autoload: GameDeveloperGodotAutoloadPlan?
    /// Explicit Cocos scene. Unity, Godot and GDevelop plans carry nil.
    public let scene: GameDeveloperInstrumentationScene?
    /// Present for GDevelop; notApplicable for the other engines.
    public let exportHandling: GameDeveloperInstrumentationExportHandling
    public let diagnostics: [GameDeveloperInstrumentationDiagnostic]
    public let dormancy: GameDeveloperInstrumentationDormancy

    public var requiresRebuild: Bool {
        if engine == .gdevelop, exportHandling == .alreadyExportedPlayable { return false }
        return descriptor.instrumentation.requiresRebuild
    }
    public var hasChanges: Bool { files.contains { $0.changed } }
    public var changedFiles: [GameRelativePath] { files.filter { $0.changed }.map { $0.path } }
    public var unchangedFiles: [GameRelativePath] { files.filter { !$0.changed }.map { $0.path } }
    public var displayName: String { descriptor.displayName }
    public var limitations: String { descriptor.instrumentation.limitations }
    public var limitationsZhHans: String { descriptor.instrumentation.limitationsZhHans }
    public var summary: String { descriptor.instrumentation.summary }
    public var summaryZhHans: String { descriptor.instrumentation.summaryZhHans }
    public var officialDocumentation: [String] { descriptor.instrumentation.officialDocumentation }
}

public struct GameDeveloperInstrumentationReceipt: Sendable, Equatable {
    public let schemaVersion: Int
    public let planID: UUID
    public let engine: GameEngineID
    public let project: GameStoredProject
    public let context: GameProjectContext
    public let previousRevision: String
    public let revision: String
    public let changedFiles: [GameRelativePath]
    public let unchangedFiles: [GameRelativePath]
    public let diagnostics: [GameDeveloperInstrumentationDiagnostic]

    public var changed: Bool { previousRevision != revision }
}

public struct GameDeveloperInstrumentationSourceBundle: Sendable, Equatable {
    public enum Role: String, Codable, Sendable {
        case helperSource
        /// Installer-generated metadata such as a Cocos `.meta` file.
        case generatedFile
        case license
        case notice
        case provenance
        case readme
        case installInstructions
    }

    public struct File: Sendable, Equatable, Identifiable {
        public let path: String
        public let role: Role
        public let sha256: String
        public let bytes: Int
        public let data: Data

        public var id: String { path }
    }

    public let schemaVersion: Int
    public let engine: GameEngineID
    public let licenseIdentifier: String
    public let sourceRevision: String
    public let files: [File]
    /// SHA-256 of the exact PROVENANCE.json bytes in `files`.
    public let manifestSHA256: String
    /// SHA-256 over sorted (path, NUL, file SHA-256) records.
    public let aggregateSHA256: String
}
